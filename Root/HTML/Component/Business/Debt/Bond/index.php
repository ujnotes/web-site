		<li><div><strong>Coupon rate</strong> — The annual interest rate paid by the issuer, usually distributed semi-annually or annually. A 6% coupon on a ₹1,000 bond pays ₹60 each year.</div></li>
		<li><div><strong>Maturity date</strong> — The specific future date when the loan ends and the issuer repays the full principal face value to the bondholder.</div></li>
