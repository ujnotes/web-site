	<h3>The bond seesaw: prices and yields</h3>
	<p>
		Bonds can be bought and sold on secondary markets before they mature. When prevailing market interest rates change, existing bond prices move in the opposite direction, like a seesaw:
	</p>
	<p>
		If current interest rates rise to 8%, nobody will pay full price for an existing bond paying only 6%. To attract buyers, the price of that 6% bond must drop until its effective yield matches current market rates. Conversely, when interest rates drop, older higher-paying bonds trade at a premium.
	</p>
