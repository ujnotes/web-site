	<h3>What is interest?</h3>
	<p>
		Interest is the fee paid by a borrower to a lender for the use of money over time, expressed as a percentage of the borrowed amount (the principal).
	</p>
	<h3>Why does interest exist?</h3>
	<p>
		Interest is the market price of time and risk, reflecting four economic realities:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Time preference</strong> — People naturally prefer having goods and resources now rather than later. When a lender lends money, they postpone their own consumption. Interest compensates them for waiting.</div></li>
		<li><div><strong>Opportunity cost</strong> — While the money is in the borrower's hands, the lender cannot use it for other profitable investments, such as starting a business or purchasing property.</div></li>
		<li><div><strong>Default risk</strong> — There is always a possibility that the borrower will be unable to repay the loan. Part of the interest rate is an insurance premium against loss.</div></li>
		<li><div><strong>Inflation</strong> — As prices rise over time, the purchasing power of money decreases. Interest ensures the lender is not repaid with currency that buys less than what was originally lent.</div></li>
	</ul>
	<h3>Simple interest</h3>
	<p>
		Simple interest is calculated strictly on the original principal:
	</p>
	<p>
		<strong>Interest = Principal × Rate × Time</strong>
	</p>
	<p>
		If you borrow ₹10,000 at 5% simple annual interest for 3 years, you pay ₹500 each year, totalling ₹1,500 in interest. The principal balance remains constant.
