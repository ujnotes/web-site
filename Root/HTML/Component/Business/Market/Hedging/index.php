	<h3>What is hedging?</h3>
	<p>
		Hedging is a risk management strategy where an investor or business takes an offsetting financial position to protect against potential losses from adverse price fluctuations. In plain terms, hedging is financial insurance.
	</p>
	<h3>An everyday analogy</h3>
	<p>
		Consider a farmer planting wheat in the spring. If wheat prices crash by harvest time in autumn, the farmer might make a heavy loss. To protect themselves, the farmer enters a contract today agreeing to sell their wheat in six months at a locked-in price.
	</p>
	<p>
		If wheat prices plunge, the contract protects the farmer. If wheat prices skyrocket, the farmer misses out on extra profits, but their business survives. The hedge eliminated the existential risk of price volatility.
	</p>
	<h3>How do hedges work in practice?</h3>
	<p>
		Hedging commonly relies on derivative contracts:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Futures and forwards</strong> — Binding agreements to buy or sell an asset (such as crude oil, currency, or grain) at a predetermined price on a future date. Airlines routinely buy jet fuel futures to protect themselves from unexpected oil price spikes.</div></li>
		<li><div><strong>Options</strong> — Contracts giving the buyer the right, but not the obligation, to buy or sell an asset at a fixed strike price. A put option acts like an insurance policy against falling stock prices.</div></li>
	</ul>
	<h3>Hedging versus speculating</h3>
	<p>
		People often confuse hedging with speculation because both use derivative markets, but their motivations are exact opposites:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Speculators accept risk</strong> — They bet on price movements with the goal of making a profit.</div></li>
		<li><div><strong>Hedgers avoid risk</strong> — They gladly pay a small fee or forgo windfall profits in order to secure predictability for their core operations.</div></li>
	</ul>
