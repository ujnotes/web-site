	</ul>
	<h3>Limited liability and residual claims</h3>
	<p>
		Two legal concepts make corporate stock powerful:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Limited liability</strong> — As a shareholder, your financial loss is strictly limited to the amount you invested. If the corporation goes bankrupt or gets sued, creditors cannot seize your personal home, car, or bank savings.</div></li>
		<li><div><strong>Residual claim</strong> — Stockholders stand last in line. If a company liquidates, bondholders, suppliers, employees, and tax authorities must be fully paid before shareholders receive any remaining assets. In exchange for taking that risk, shareholders enjoy unlimited upside when the company thrives.</div></li>
	</ul>
	<h3>Primary versus secondary markets</h3>
	<p>
		When a company first sells shares to the public to raise capital for factories or research, it does so in the <strong>primary market</strong> through an Initial Public Offering (IPO).
	</p>
	<p>
		After that initial sale, those shares trade continuously between investors on the <strong>secondary market</strong> (the stock exchange). In secondary trading, money flows between investors, not to the company itself.
