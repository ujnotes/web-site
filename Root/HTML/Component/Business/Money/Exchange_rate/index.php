	<h3>Key forces driving currency values</h3>
	<p>
		Five main economic factors dictate whether a currency strengthens or weakens:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Trade balance (Exports vs Imports)</strong> — When a country exports goods that global buyers demand, foreigners must purchase the exporter's local currency to pay for them, driving up its value. Heavy net importers constantly sell local currency to buy foreign goods, putting downward pressure on their exchange rate.</div></li>
		<li><div><strong>Interest rates</strong> — Central banks set benchmark interest rates. Higher interest rates offer lenders better returns than other nations, attracting foreign investment capital and strengthening the currency.</div></li>
		<li><div><strong>Inflation differentials</strong> — A country with persistently high inflation sees its domestic purchasing power erode rapidly. According to Purchasing Power Parity (PPP), high-inflation currencies tend to depreciate against currencies with lower inflation.</div></li>
		<li><div><strong>Public debt and economic stability</strong> — Countries with stable governments, strong rule of law, and manageable debt attract international confidence. Political turmoil or risk of debt default triggers rapid capital flight.</div></li>
		<li><div><strong>Speculation and reserve status</strong> — Currencies like the US dollar or Swiss franc function as "safe havens." During global crises, international investors rush into them, temporarily boosting their value regardless of trade deficits.</div></li>
