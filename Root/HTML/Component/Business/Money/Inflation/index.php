	<h3>What is inflation?</h3>
	<p>
		Inflation is the gradual, sustained increase in the general level of prices for goods and services across an economy over time. As prices rise, each unit of currency buys fewer goods than it did before: inflation is the erosion of money's purchasing power.
	</p>
	<h3>What causes inflation?</h3>
	<p>
		Economists categorize inflation by its underlying triggers:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Demand-pull inflation</strong> — Occurs when consumer and business demand grows faster than the economy's capacity to produce goods. When "too much money chases too few goods," sellers naturally raise prices.</div></li>
		<li><div><strong>Cost-push inflation</strong> — Occurs when the cost of essential production inputs—such as crude oil, raw materials, or shipping—spikes. Businesses pass these increased operating costs on to consumers in higher retail prices.</div></li>
		<li><div><strong>Money supply expansion</strong> — If a government or central bank increases the money supply significantly faster than the actual output of real goods and services, the value of each individual monetary unit inevitably falls.</div></li>
	</ul>
	<h3>Winners and losers from inflation</h3>
	<p>
		Inflation does not affect everyone equally:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Borrowers win</strong> — If you borrowed money on a fixed interest rate, you repay the debt with future currency that has less purchasing power than when you borrowed it.</div></li>
		<li><div><strong>Savers and fixed-income earners lose</strong> — Cash stored in savings accounts earning low interest steadily loses real value, and pensioners living on fixed payments struggle as the cost of living escalates.</div></li>
	</ul>
	<h3>How do central banks fight inflation?</h3>
	<p>
		Central banks use monetary policy to manage inflation, usually targeting a moderate annual rate around 2% to 4%. When inflation surges too high, central banks raise benchmark interest rates, making borrowing more expensive, cooling demand, and restoring price stability.
