	<h3>What is plastic money?</h3>
	<p>
		Plastic money refers to payment cards—primarily debit cards and credit cards—made of plastic with embedded magnetic stripes or microchips that allow people to pay for goods and services without carrying physical cash.
	</p>
	<h3>Debit versus credit</h3>
	<p>
		Though they look identical, debit and credit cards represent two completely different financial mechanisms:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Debit cards</strong> — Deduct money directly from your existing bank account balance in real time. You are spending money you already own.</div></li>
		<li><div><strong>Credit cards</strong> — Draw on a pre-approved revolving line of credit extended by the card issuer. The bank pays the merchant immediately on your behalf, and you receive an itemised bill at the end of the month to settle the debt.</div></li>
	</ul>
	<h3>How does a card transaction work?</h3>
	<p>
		When you tap or insert a card at a payment terminal, an intricate series of digital handshakes happens in under two seconds:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>1. Terminal to Acquirer</strong> — The point-of-sale machine encrypts your card details and sends the request to the merchant's bank (the acquiring bank).</div></li>
		<li><div><strong>2. Payment Network</strong> — The acquirer routes the transaction through a global payment network such as Visa, Mastercard, RuPay, or American Express.</div></li>
		<li><div><strong>3. Card Issuer Approval</strong> — The network contacts your bank (the issuing bank), which checks available funds or credit limit, screens for fraud, and returns an approval code back through the chain.</div></li>
	</ul>
	<h3>Benefits and risks</h3>
	<p>
		Plastic money dramatically reduced the risk of carrying large bundles of paper cash and made cross-border purchases and online commerce seamless. It also provides fraud protections where compromised cards can be blocked instantly.
	</p>
	<p>
		However, credit cards can easily become debt traps. Because swiping plastic decouples the psychological pain of parting with physical cash from the purchase, consumers often overspend, incurring steep compound interest rates on unpaid revolving balances.
