	<h3>Present with confidence</h3>
	<p>
		A good presentation is a guided conversation. The slides provide a clear path; your voice, examples and answers provide the detail. The aim is not to display everything you know, but to help this audience understand and remember the most important idea.
	</p>
	<h2>Before you present</h2>
	<h4>Have no fear</h4>
	<p>
		Stage fear is normal, but it does not have to lead the presentation. Treat the audience as allies who want to understand what you are building.
	</p>
	<p>
		Use affirmative self-talk rather than negative commands. Give yourself clear instructions such as: “I am prepared.” “I speak clearly.” “I will connect with this audience.” These statements focus attention on the behaviour you want.
	</p>
	<h4>Introduce yourself</h4>
	<p>
		Start simply:
	</p>
	<ul class="list-bullet content-list">
		<li><div>Name</div></li>
		<li><div>Role</div></li>
	</ul>
	<p>
		Do not begin with a long history. Give the audience a frame for listening, then move to the problem and the idea.
	</p>
	<h4>Know your audience</h4>
	<p>
		Adapt the presentation to the people in front of you. Ask:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Who</strong> is listening?</div></li>
		<li><div><strong>Where</strong> are they and what context do they bring?</div></li>
		<li><div><strong>Why</strong> are they here?</div></li>
		<li><div><strong>What</strong> do they need to understand or decide?</div></li>
		<li><div><strong>When</strong> will they use this information or take action?</div></li>
	</ul>
	<h4>Prepare thoroughly</h4>
	<p>
		Memorize the presentation like a poem. Rehearse the order, transitions and opening and closing lines until you can speak naturally without depending on the slides.
	</p>
	<h2>How to present</h2>
	<h4>Keep slides minimalist</h4>
	<p>
		Do not crowd the slide. Use a small number of words, strong visual hierarchy and generous empty space. The slide is a prompt for the audience, not the complete speech.
	</p>
	<h4>Choose attire and body language deliberately</h4>
	<p>
		Wear something appropriate that does not distract from the message. Connect with the audience through an open posture, natural movement and steady eye contact.
	</p>
	<h4>Assume goodwill</h4>
	<p>
		Imagine that the audience is an ally—or, in the memorable metaphor, an angel who genuinely wants to hear you. This makes the presentation collaborative rather than adversarial.
	</p>
	<h4>Modulate your voice</h4>
	<p>
		Avoid a monotone. Vary pace, volume, pauses and emphasis. A little animation helps the audience sense what matters.
	</p>
	<h4>Show the team’s strengths</h4>
	<p>
		Introduce the team and explain each member’s role and specific strength. Make clear why this combination of people is capable of solving the problem.
	</p>
	<h2>A clear startup slide story</h2>
	<h4>Company name and vision</h4>
	<p>
		Open with the company name and a concise statement of the vision. Make the promise easy to repeat.
	</p>
	<h4>1. Problem</h4>
	<p>
		Set the stage before presenting the solution.
	</p>
	<ul class="list-bullet content-list">
		<li><div>What problem exists?</div></li>
		<li><div>How are people affected?</div></li>
		<li><div>Why does it matter now?</div></li>
	</ul>
	<h4>2. Target audience</h4>
	<p>
		Explain who you are targeting and where they are. Be specific about the first users or customers rather than describing everyone.
	</p>
	<h4>3. Solution</h4>
	<p>
		Explain whether the offering is a product, a service or a combination.
	</p>
	<ul class="list-bullet content-list">
		<li><div>What does it do?</div></li>
		<li><div>What is its unique selling proposition?</div></li>
		<li><div>What alternatives do people use today?</div></li>
		<li><div>Why is this approach better or meaningfully different?</div></li>
	</ul>
	<h4>Team</h4>
	<p>
		Connect the team’s strengths to the problem. Each person should have a clear contribution.
	</p>
	<h2>Speech, slides and Q&amp;A</h2>
	<p>
		Put the structure and the essential idea on the slides. Put examples, explanation and nuance in the speech. Keep detailed data, assumptions and supporting numbers ready for the Q&amp;A or backup slides.
	</p>
	<p>
		This division keeps the main presentation easy to follow while still showing that the team has done the deeper work.
	</p>
