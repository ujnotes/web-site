	<h3>The double coincidence of wants</h3>
	<p>
		The greatest structural problem with barter is the <strong>double coincidence of wants</strong>. For a trade to occur, person A must want exactly what person B has, and person B must want exactly what person A has, at the exact same time and in compatible quantities.
	</p>
	<p>
		If a farmer has extra wheat and needs a pair of boots, they must find a cobbler who happens to need wheat right now. If the cobbler already has plenty of wheat, no trade can happen until the farmer trades wheat for something else the cobbler wants.
	</p>
	<h3>Other limits of barter</h3>
	<p>
		Beyond the coincidence of wants, direct barter suffers from three major hurdles:
	</p>
