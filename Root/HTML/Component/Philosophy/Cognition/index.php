		<?php $alt='A quiet desk where scattered observations are organized into a coherent map'; require('../HTML/Fragment/Component_cover.php') ?>
	<h2 class='center'><?php echo $desc; ?></h2>
	<h3>What is cognition?</h3>
	<p>
		Cognition is the process by which information is acquired, organized and used.
	</p>
	<p>
		When you notice a sound, recognize a face, remember a name, imagine tomorrow or decide where to go—you are using cognition.
	</p>
	<p>
		It includes perception, attention, memory, language, learning, reasoning and decision-making.
	</p>
	<p>
		Cognition is not one thing happening at one place. It is the whole movement of information through the mind.
	</p>
	<h3>Where does cognition begin?</h3>
	<p>
		It begins with change.
	</p>
	<p>
		Light reaches the eyes. Pressure reaches the skin. Vibrations reach the ears. The body itself also sends information about hunger, pain, balance and position.
	</p>
	<p>
		But the mind does not receive the world exactly as it is.
	</p>
	<p>
		The eyes do not deliver a picture. They deliver signals. The brain must organize those signals into edges, colours, distance, objects and movement.
	</p>
	<p>
		What we experience as the obvious world is already an interpretation.
	</p>
	<h3>Is perception the same as seeing?</h3>
	<p>
		No.
	</p>
	<p>
		Seeing is not merely receiving light. Perception is deciding what that light means.
	</p>
	<p>
		A shadow on the floor may first appear to be a hole. A rope in darkness may be mistaken for a snake.
	</p>
	<p>
		The signal has not necessarily changed. The interpretation has.
	</p>
	<p>
		Perception combines the present signal with memory and expectation. This makes it fast and useful. It also makes it fallible.
	</p>
	<p>
		We do not simply see and then think. Thinking is already present in the act of seeing.
	</p>
	<h3>What is attention?</h3>
	<p>
		Attention is the selection of what will be processed more deeply.
	</p>
	<p>
		At any moment, more information reaches us than we can use. The feeling of our clothes, the hum of a fan and objects at the edge of sight may all be present, yet remain unnoticed.
	</p>
	<p>
		Attention brings one part of this field forward.
	</p>
	<p>
		It is like a lamp in a dark room. What it illuminates becomes clear; what remains outside it may still exist, but has less influence on thought.
	</p>
	<p>
		This is why two people can stand in the same place and later remember different things. They were exposed to the same scene, but did not attend to the same world.
	</p>
	<h3>What is memory?</h3>
	<p>
		Memory is not a perfect recording of the past.
	</p>
	<p>
		It is the ability to preserve information well enough for it to affect the present.
	</p>
	<p>
		Some memories last only long enough to complete an action. Others become knowledge, skill or parts of one's identity.
	</p>
	<p>
		When a memory is recalled, the mind reconstructs it. Missing pieces may be filled using expectation, later knowledge or imagination.
	</p>
	<p>
		This is why a memory can feel certain and still be wrong.
	</p>
	<p>
		The past we use is not always the past exactly as it happened. It is the past as the present mind can rebuild it.
	</p>
	<h3>How are concepts formed?</h3>
	<p>
		The mind groups different experiences by what they share.
	</p>
	<p>
		No two chairs are exactly alike. Yet after seeing only a few, a child learns the concept of a chair and recognizes one never seen before.
	</p>
	<p>
		A concept is therefore a compressed pattern. It lets the mind treat many different things as members of one useful kind.
	</p>
	<p>
		Without concepts, every object and event would be entirely new. Thought would drown in detail.
	</p>
	<p>
		But concepts can also hide differences. A label makes thinking efficient, though it can make us believe that the boundary drawn by the mind must also exist sharply in the world.
	</p>
	<h3>What is thought?</h3>
	<p>
		A thought is a partial internal simulation.
	</p>
	<p>
		The mind can represent an object that is absent, replay an event that has ended or imagine one that has never happened.
	</p>
	<p>
		This makes planning possible.
	</p>
	<p>
		Before moving a heavy table through a narrow door, one can rotate it in the mind. The imagined attempt may fail, saving the body from making the real one.
	</p>
	<p>
		Thought allows reality to be tested cheaply.
	</p>
	<p>
		But a simulation is only as good as its model. If an important fact is missing, a perfectly reasoned thought can still lead to the wrong conclusion.
	</p>
	<h3>How does cognition guide action?</h3>
	<p>
		Cognition does not end with knowing. It prepares action.
	</p>
	<p>
		Perception describes the situation. Memory provides earlier experience. Concepts simplify it. Thought simulates possibilities. Emotion assigns urgency and value. A decision selects what is to be done.
	</p>
	<p>
		These processes are not always separate or orderly. They influence one another continuously.
	</p>
	<p>
		Fear changes what is noticed. Attention changes what is remembered. Memory changes what is perceived. The action then changes the world, producing new information, and the cycle begins again.
	</p>
	<h3>Is cognition rational?</h3>
	<p>
		Not always.
	</p>
	<p>
		The mind was not built to discover perfect truth in every situation. It evolved to help a living body act quickly with limited information and limited energy.
	</p>
	<p>
		Shortcuts are therefore necessary.
	</p>
	<p>
		Usually these shortcuts work. Sometimes they become biases: we notice evidence that supports what we already believe, judge an event by what is easiest to remember, or mistake confidence for accuracy.
	</p>
	<p>
		A cognitive error is not proof that cognition is useless. It is the cost of making decisions before everything is known.
	</p>
	<p>
		The answer is not to abandon intuition, but to know when it should be checked.
	</p>
	<h3>Is cognition the same as intelligence?</h3>
	<p>
		Cognition is the larger set of processes by which information moves through a system.
	</p>
	<p>
		Intelligence describes how effectively those processes produce understanding and useful action.
	</p>
	<p>
		A person who remembers a telephone number is using cognition. A person who recognizes the pattern behind a difficult problem is displaying intelligence.
	</p>
	<p>
		The two overlap, but they are not identical.
	</p>
	<h3>Is cognition the same as consciousness?</h3>
	<p>
		No.
	</p>
	<p>
		Much cognition occurs without entering awareness.
	</p>
	<p>
		The brain adjusts balance while we walk, predicts the next sound in a familiar word and filters countless sensations without asking the conscious 'I' for permission.
	</p>
	<p>
		Conscious experience seems to receive only a small part of the work being done.
	</p>
	<p>
		Cognition is the processing of information. Consciousness is the experience—and perhaps the direction—of some of that processing.
	</p>
	<h3>So what is cognition, finally?</h3>
	<p>
		Cognition is how a mind turns signals into a usable world.
	</p>
	<p>
		It selects, interprets, remembers, groups, imagines, values and decides.
	</p>
	<p>
		We do not act upon reality directly. We act upon the model of reality that cognition builds.
	</p>
	<p>
		To understand cognition is therefore to understand both the remarkable power of the mind and the many ways in which it can be mistaken.
	</p>

</div>

