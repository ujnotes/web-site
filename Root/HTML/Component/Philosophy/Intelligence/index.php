	<h2 class='center'><?php echo $desc; ?></h2>
	<h3>What is intelligence?</h3>
	<p>
		Intelligence is the ability to understand a situation and find an effective response to it.
	</p>
	<p>
		A key may open one lock perfectly. But we do not call the key intelligent. It cannot understand why the lock is closed, try another way, or learn from failure.
	</p>
	<p>
		An intelligent system does more than produce an answer. It notices what matters, connects it with what it already knows, imagines what may happen next and chooses what to do.
	</p>
	<p>
		In short, intelligence is the ability to turn information into useful action.
	</p>
	<h3>Is intelligence the same as knowledge?</h3>
	<p>
		No.
	</p>
	<p>
		Knowledge is what is known. Intelligence is how that knowledge is used.
	</p>
	<p>
		A library may contain more knowledge than any person who enters it. Yet the library cannot decide which book will solve a particular problem.
	</p>
	<p>
		Likewise, a person may remember many facts and still fail to apply them. Another person may know less, but see the important connection and reach the better solution.
	</p>
	<p>
		Knowledge gives intelligence material to work with. But more material does not by itself make the worker better.
	</p>
	<h3>How does intelligence work?</h3>
	<p>
		Intelligence begins by forming a model of the situation.
	</p>
	<p>
		This model does not have to contain everything. It only needs to preserve the parts that matter.
	</p>
	<p>
		If one is trying to cross a road, the colour of a nearby building may not matter. The speed and direction of the approaching car does.
	</p>
	<p>
		The intelligent act is partly in knowing the difference.
	</p>
	<p>
		Using such a model, the mind can run small simulations:
	</p>
	<ul class="list-bullet content-list">
		<li><div>If I do this, what may happen?</div></li>
		<li><div>What am I missing?</div></li>
		<li><div>Which possibility is most likely?</div></li>
		<li><div>What is the cost if I am wrong?</div></li>
	</ul>
	<p>
		The response is then chosen not merely from what is visible now, but from the futures that can be imagined.
	</p>
	<h3>What is reasoning?</h3>
	<p>
		Reasoning is the process of moving from what is known to what follows from it.
	</p>
	<p>
		If every door of a room is locked from the inside, but one window is open, the open window becomes important. It may not prove how someone entered, but it changes which explanation is more likely.
	</p>
	<p>
		Reasoning connects facts. Good reasoning also measures how strong that connection is.
	</p>
	<p>
		This is especially important because we almost never possess all the facts.
	</p>
	<p>
		Intelligence therefore does not only ask, “What is true?” It must also ask, “How sure am I?”
	</p>
	<h3>What is understanding?</h3>
	<p>
		To understand something is to possess a useful model of how its parts relate.
	</p>
	<p>
		One may memorize that pressing a switch turns on a lamp. But understanding begins when one can explain the path from the switch to the wire, the current and the light—and can predict what may be wrong when the lamp does not turn on.
	</p>
	<p>
		Understanding allows knowledge to travel.
	</p>
	<p>
		A memorized answer works only for the old question. An understood principle can be applied to a new one.
	</p>
	<h3>Can intelligence learn?</h3>
	<p>
		It must.
	</p>
	<p>
		A response that never changes with experience is merely a fixed rule.
	</p>
	<p>
		Learning is the correction of the model. When prediction and reality disagree, an intelligent system should discover why and adjust.
	</p>
	<p>
		But learning is not simply storing every experience. That would be like keeping every stone one has ever seen in order to understand a mountain.
	</p>
	<p>
		Learning requires compression: many experiences are reduced into a smaller pattern.
	</p>
	<p>
		A child does not need to touch every flame to learn that fire can burn.
	</p>
	<h3>Is speed a sign of intelligence?</h3>
	<p>
		Sometimes, but not always.
	</p>
	<p>
		A calculator can multiply numbers faster than a person. A search engine can retrieve a fact in an instant. Speed makes an ability useful, but it does not define the ability.
	</p>
	<p>
		An answer given slowly may be intelligent if the problem is difficult. An answer given quickly may be foolish if the important question was never examined.
	</p>
	<p>
		Intelligence is better measured by the quality of the model, the accuracy of the prediction and the suitability of the action.
	</p>
	<h3>Can a machine be intelligent?</h3>
	<p>
		A machine can certainly perform intelligent acts.
	</p>
	<p>
		It can detect patterns, compare possibilities, learn from examples and select actions that achieve a goal. In some narrow tasks, it can do so far better than any person.
	</p>
	<p>
		But intelligence is not the same as consciousness.
	</p>
	<p>
		A system may find a solution without experiencing the problem. It may produce language about pain without feeling pain, just as a thermometer can measure heat without feeling warm.
	</p>
	<p>
		Whether a machine understands in the same way that we do is a separate question. We should not confuse a useful output with an inner experience merely because both are expressed in words.
	</p>
	<h3>Is intelligence always good?</h3>
	<p>
		No.
	</p>
	<p>
		Intelligence serves the goal it is given—or the goal it has learned to pursue.
	</p>
	<p>
		A clever thief and a good doctor may both be intelligent. What separates them is not their ability to solve a problem, but the problem they choose to solve and the value they assign to others.
	</p>
	<p>
		Intelligence tells us how to reach a destination. It does not, by itself, tell us which destination is worth reaching.
	</p>
	<p>
		For that we need knowledge, compassion and wisdom.
	</p>
	<h3>So what is intelligence, finally?</h3>
	<p>
		Intelligence is the ability to build useful models, discover patterns, reason under uncertainty, learn from error and choose effective action.
	</p>
	<p>
		It is not a collection of facts, nor speed alone, nor consciousness itself.
	</p>
	<p>
		It is the bridge between what is known and what can be done.
	</p>

</div>

