	<h3>What is a law?</h3>
	<p>
		A law can describe how something behaves, express a relationship that follows from stated assumptions, or prescribe how people are expected to act.
	</p>
	<p>
		These are different uses of the same word.
	</p>
	<p>
		The law of gravitation, a law of arithmetic, a traffic law and Murphy’s law do not get their authority from the same place. Calling each one a “law” does not make them equally certain, equally universal or equally enforceable.
	</p>
	<p>
		A useful first question is: <strong>What kind of claim is this?</strong>
	</p>
	<h3>A practical map of laws</h3>
	<p>
		I find it useful to distinguish six broad kinds:
	</p>
	<table>
		<tr><td>Kind</td><td>What it does</td><td>Examples</td></tr>
		<tr><td>Formal laws and theorems</td><td>State relationships within a defined system</td><td>Laws of arithmetic, probability theorems, information-theory limits</td></tr>
		<tr><td>Laws of nature</td><td>Describe regularities in the physical and living world</td><td>Laws of motion, thermodynamics, inheritance</td></tr>
		<tr><td>Social and behavioural regularities</td><td>Describe patterns in human behaviour and institutions</td><td>Economic laws, psychological laws, population patterns</td></tr>
		<tr><td>Legal laws</td><td>Establish recognised rights, duties, powers and procedures</td><td>International law, national legislation, local regulations</td></tr>
		<tr><td>Other normative rules</td><td>Express expectations about conduct or participation</td><td>Ethical principles, customs, organisational rules, game rules</td></tr>
		<tr><td>Informal laws</td><td>Capture a recurring observation or practical warning</td><td>Murphy’s law, Parkinson’s law, rules of thumb</td></tr>
	</table>
	<p>
		This is a working map, not a universally agreed classification. The categories overlap. A mathematical result can describe a physical system, and a social custom can become legally recognised.
	</p>
	<h2>Why not put everything under “natural” and “man-made”?</h2>
	<p>
		That distinction is useful, but incomplete.
	</p>
	<p>
		Humans formulate scientific laws, yet the phenomena they describe do not depend on a legislature approving them. Humans also formulate mathematical systems, but a result within a system cannot be changed merely by voting for a different answer.
	</p>
	<p>
		Meanwhile, human behaviour is part of nature, even though its patterns are shaped by culture, institutions and deliberate choices.
	</p>
	<p>
		We therefore need to distinguish <strong>what a law concerns</strong> from <strong>what justifies it</strong>.
	</p>
	<h3>Formal laws: what follows from assumptions?</h3>
	<p>
		Mathematics, logic and probability establish relationships through definitions, axioms and valid reasoning.
	</p>
	<p>
		For ordinary numbers, addition is commutative: changing the order does not change the sum. Three plus five equals five plus three.
	</p>
	<p>
		But the setting matters. Matrix multiplication generally does not have this property. A familiar mathematical rule cannot simply be transferred to every operation carrying the same name.
	</p>
	<p>
		A theorem is proved from specified assumptions. An axiom is a starting assumption of a system. They have different roles; neither becomes more reliable merely by being called a law. <a class="content-link" href="https://live.ocw.mit.edu/courses/6-1200j-mathematics-for-computer-science-spring-2024/mit6_1200j_s24_lec01.pdf" target="_blank" rel="noopener noreferrer">MIT: predicates, sets and proofs</a>
	</p>
	<p>
		Information theory belongs partly here. Shannon’s work establishes mathematical limits on communication and compression under defined models. Applying those results to a real communication system requires checking whether the model fits that system. <a class="content-link" href="https://www.nokia.com/bell-labs/publications-and-media/publications/a-mathematical-theory-of-communication/" target="_blank" rel="noopener noreferrer">Shannon: A Mathematical Theory of Communication</a>
	</p>
	<p>
		Other examples include results in computation, algorithms and networks.
	</p>
	<p>
		The distinction matters: a proved limit and a technological trend are different kinds of claims, even when both are described as laws.
	</p>
	<h3>Laws of nature: what does the world do?</h3>
	<p>
		Scientific laws describe regularities supported by observation and experiment. They help us explain relationships and predict outcomes.
	</p>
	<p>
		These include:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Physical laws:</strong> motion, gravitation, electromagnetism and thermodynamics.</div></li>
		<li><div><strong>Chemical laws:</strong> relationships involving composition, reactions and gases.</div></li>
		<li><div><strong>Biological regularities:</strong> inheritance and relationships involving living organisms.</div></li>
		<li><div><strong>Ecological and Earth-system regularities:</strong> relationships involving populations, resources, climate and geological processes.</div></li>
	</ul>
	<p>
		These subjects are connected. A living organism must also satisfy physical and chemical constraints.
	</p>
	<p>
		Our formulations have conditions and limits. A gas law may describe an idealised gas. Newtonian mechanics is extremely useful within its familiar range, while other conditions require relativity or quantum mechanics.
	</p>
	<p>
		When observations conflict with a scientific law, we investigate the measurement, assumptions and formulation. We do not prosecute nature for disobedience.
	</p>
	<p>
		Nor does a scientific theory graduate into a law after enough evidence. Laws and theories have different roles in scientific explanation; “theory” does not simply mean an unconfirmed guess. <a class="content-link" href="https://openstax.org/books/college-physics/pages/1-1-physics-an-introduction" target="_blank" rel="noopener noreferrer">OpenStax: physics, laws and theories</a>
	</p>
	<p>
		Biology especially requires care about scope. Mendel’s laws illuminate inheritance, but nearby genes on the same chromosome can be inherited together rather than assorting independently. The conditions belong with the statement of the law. <a class="content-link" href="https://openstax.org/books/biology-2e/pages/13-1-chromosomal-theory-and-genetic-linkage" target="_blank" rel="noopener noreferrer">OpenStax: genetic linkage</a>
	</p>
	<p>
		Exactly what makes a regularity a law of nature remains a philosophical question. We should not mistake this practical classification for a settled account of what laws ultimately are. <a class="content-link" href="https://plato.stanford.edu/entries/laws-of-nature/" target="_blank" rel="noopener noreferrer">Stanford Encyclopedia of Philosophy: laws of nature</a>
	</p>
	<h3>Social laws: a pattern or an obligation?</h3>
	<p>
		“Social law” is particularly ambiguous.
	</p>
	<p>
		It can mean a proposed pattern in how people behave. It can also mean a rule that a community expects people to follow.
	</p>
	<p>
		The first is descriptive. The second is normative: it concerns what people should, must or may do.
	</p>
	<p>
		In the descriptive sense, examples come from economics, psychology, sociology and demography. The law of demand describes how quantity demanded typically responds to price, with other relevant conditions held constant.
	</p>
	<p>
		That qualification matters. Changes in income, expectations or the product itself can change the outcome. <a class="content-link" href="https://openstax.org/books/principles-economics-2e/pages/3-2-shifts-in-demand-and-supply-for-goods-and-services" target="_blank" rel="noopener noreferrer">OpenStax: demand, supply and other things being equal</a>
	</p>
	<p>
		Social regularities can be useful without predicting every individual. They can also change as people adapt to incentives, learn about a prediction or change their institutions.
	</p>
	<p>
		A recurring social pattern is not automatically desirable or inevitable. Explaining discrimination, for example, does not justify it.
	</p>
	<h3>Legal laws: what have societies established?</h3>
	<p>
		Legal laws establish rights, duties, prohibitions, powers and procedures through sources recognised by a legal system.
	</p>
	<p>
		They can prohibit conduct, but they can also create institutions, recognise ownership, define citizenship, authorise decisions and provide ways to settle disputes.
	</p>
	<p>
		They can be classified along several different dimensions.
	</p>
	<h2>By jurisdiction</h2>
	<ul class="list-bullet content-list">
		<li><div><strong>International law:</strong> rules concerning states and other subjects of international law, including rules derived from treaties, custom and general principles.</div></li>
		<li><div><strong>Regional or supranational law:</strong> rules operating within particular regional arrangements, with powers that depend on those arrangements.</div></li>
		<li><div><strong>National law:</strong> law within a country.</div></li>
		<li><div><strong>State, provincial or other subnational law:</strong> law within constituent territories where the constitutional system provides for it.</div></li>
		<li><div><strong>Local law:</strong> municipal rules and bylaws within the authority given to local bodies.</div></li>
	</ul>
	<p>
		International law is not simply the top rung of a single worldwide legislative ladder. Its relationship with domestic law depends on the relevant legal systems and obligations. <a class="content-link" href="https://treaties.un.org/Pages/overview.aspx?path=overview%2Fdefinition%2Fpage1_en.xml" target="_blank" rel="noopener noreferrer">United Nations Treaty Collection: sources and instruments</a>
	</p>
	<h2>By source or legal function</h2>
	<p>
		Constitutions, legislation, delegated regulations, judicial decisions and legally recognised customs can have different roles. Their authority varies between systems.
	</p>
	<p>
		“Man-made” does not mean that every law was written by a legislature. Law can also develop through courts and custom.
	</p>
	<h2>By subject</h2>
	<p>
		Examples include constitutional, administrative, criminal, contract, property, family, labour, tax, environmental and human-rights law.
	</p>
	<p>
		These are overlapping classifications. A single provision can be national in jurisdiction, statutory in source and environmental in subject.
	</p>
	<p>
		Legal validity also does not settle moral rightness. A law can be recognised and enforced while still deserving criticism or reform.
	</p>
	<h3>Other rules: ethics, customs, organisations and games</h3>
	<p>
		Not every rule people follow is a law of the state.
	</p>
	<p>
		Ethical principles concern right and wrong. Customs and etiquette shape social expectations. Religious rules guide conduct within traditions. Organisations establish policies, professions develop codes, and games specify permitted moves.
	</p>
	<p>
		Some of these rules acquire legal force in particular settings; others do not.
	</p>
	<p>
		There is also an ambiguity in the phrase <strong>“natural law.”</strong> In legal and moral philosophy, it can refer to principles of right conduct grounded in accounts of human nature or reason. That is a different use from the scientific “laws of nature.”
	</p>
	<p>
		When a rule invokes nature, we should still ask whether it is describing what happens or arguing for what ought to happen.
	</p>
	<h3>Informal laws: useful observations without guarantees</h3>
	<p>
		<a class="content-link XURL" href="/philosophy/murphys_law" data-target="philosophy/murphys_law" data-title="Murphy’s law">Murphy’s law</a> belongs here.
	</p>
	<p>
		Its familiar wording—“Anything that can go wrong will go wrong”—is not a scientific guarantee that every possible failure will occur. Its practical value is to remind us to anticipate failure and remove avoidable opportunities for it.
	</p>
	<p>
		Other informal laws describe tendencies in work, organisations, technology or everyday life. Some are jokes, some are useful summaries of experience, and some inspire testable hypotheses.
	</p>
	<p>
		Their usefulness depends on how well they fit the situation.
	</p>
	<p>
		Calling an observation a law can make it memorable. It does not supply proof or evidence.
	</p>
	<h3>How should we judge a law?</h3>
	<p>
		The word alone tells us too little. Ask:
	</p>
	<ol class="list-bullet content-list">
		<li><div><strong>What does it claim?</strong> A relationship, a tendency, an obligation or a warning?</div></li>
		<li><div><strong>What supports it?</strong> Proof, observation, recognised authority, moral argument or experience?</div></li>
		<li><div><strong>Where does it apply?</strong> Which assumptions, conditions, populations or jurisdictions?</div></li>
		<li><div><strong>What would a counterexample mean?</strong> A faulty proof, an incomplete model, a limited tendency or a breach of a rule?</div></li>
		<li><div><strong>What consequences follow?</strong> A prediction, a practical precaution, a legal obligation or a moral judgement?</div></li>
	</ol>
	<p>
		A mathematical theorem, a scientific law, a legal rule and an informal saying each deserve to be understood on their own terms.
	</p>
	<p>
		We can change a speed limit through a legal process. We can improve our understanding of motion through investigation. We can use Murphy’s law to arrange a task more safely.
	</p>
	<p>
		Good judgement begins by recognising which kind of law we are dealing with.
	</p>
