	</p>
	<h3>What does it explain?</h3>
	<p>
		Ohm's law lets engineers predict current through a resistor, voltage drops in a circuit and power dissipation.
	</p>
	<p>
		Combined with Kirchhoff's laws, it supports the analysis of large networks.
	</p>
	<h3>What are its limits?</h3>
	<p>
