	<h3>What is resistance?</h3>
	<p>
		Resistance is the ratio between voltage and current for an ideal ohmic component: <strong>R = V/I</strong>.
	</p>
	<p>
		It is measured in ohms.
	</p>
	<p>
		At the microscopic level, moving charge carriers scatter from atoms, defects, vibrations and other carriers. Geometry and material determine the result.
	</p>
	<h3>What changes resistance?</h3>
	<p>
		Temperature, light, mechanical strain, magnetic fields and frequency can all affect resistance.
	</p>
	<p>
		A metal often increases in resistance as it heats. A thermistor, photoconductor or strain gauge is designed to make such dependence useful.
	</p>
	<h3>Why is it important?</h3>
	<p>
		Resistance controls current, divides voltage, dissipates energy and helps circuits interact with sensors and loads.
	</p>
	<p>
		It also limits fault current and converts electrical behavior into measurable heat or voltage.
	</p>
	<h3>Limits</h3>
	<p>
		Not every device obeys Ohm's law. Diodes, lamps, transistors and many materials have nonlinear or changing relationships.
	</p>
	<p>
		Resistance is therefore a model of behavior under stated conditions, not a universal substance inside every component.
	</p>
