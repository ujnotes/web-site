	<h3>What is Coulomb's law?</h3>
	<p>
		Coulomb's law is the physical law that quantifies the electrostatic force of attraction or repulsion between two stationary, electrically charged particles.
	</p>
	<p>
		Formulated experimentally by French physicist Charles-Augustin de Coulomb in 1785 using a sensitive torsion balance, the law states: <strong>F = k_e (|q₁ q₂| / r²)</strong>, where q₁ and q₂ are the quantities of charge, r is the separation distance between them, and k_e is Coulomb's constant.
	</p>
	<h3>How does the electrostatic force behave?</h3>
	<p>
		The electrostatic force follows three straightforward physical rules:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Like charges repel</strong>: two positive charges or two negative charges exert mutually repulsive forces that push them apart.</div></li>
		<li><div><strong>Opposite charges attract</strong>: a positive charge and a negative charge exert attractive forces that pull them toward each other.</div></li>
		<li><div><strong>Inverse-square drop</strong>: the force weakens rapidly with distance. Doubling the distance between two charges slashes the force to one-quarter; tripling the distance reduces it to one-ninth.</div></li>
	</ul>
	<p>
		By Newton's third law of motion, the force that charge 1 exerts on charge 2 is strictly equal in magnitude and opposite in direction to the force that charge 2 exerts on charge 1, regardless of which charge is larger.
	</p>
	<h3>The medium and the electric constant</h3>
	<p>
		In a vacuum, Coulomb's constant has the value <strong>k_e ≈ 8.988 × 10⁹ N·m²/C²</strong>. It is frequently written in terms of the permittivity of free space (ε₀) as <strong>k_e = 1 / (4πε₀)</strong>.
	</p>
	<p>
		When charges are placed inside an insulating material medium—such as water, oil, or glass—the molecules of the medium polarize, setting up an opposing internal field that shields the charges from one another. This reduces the effective electrostatic attraction by the material's relative permittivity (dielectric constant). In water, the force drops to roughly one-eightieth of its vacuum strength, which is why water dissolves ionic salts so readily.
	</p>
	<h3>From point charges to electric fields</h3>
	<p>
		Coulomb's law describes an interaction between separated objects across empty space. To understand how that force transmits, physics defines the concept of the <strong>electric field</strong>: any charge creates an electric field in the space surrounding itself, and a second charge experiences a force directly from the local field at its own location: <strong>E = F / q</strong>.
	</p>
	<p>
		Summing the Coulomb forces produced by continuous charge distributions leads directly to Gauss's law—the first of Maxwell's four equations that form the foundation of classical electromagnetism.
	</p>
	<h3>Limits of the law</h3>
	<p>
		Coulomb's law holds strictly for point charges that are stationary relative to one another.
	</p>
	<p>
		When charges move, they generate magnetic fields in addition to electric fields. Furthermore, disturbances in the electromagnetic field travel at the finite speed of light rather than acting instantaneously across space. In dynamic systems, electrostatic force must be expanded into the complete Lorentz force and Maxwell's equations.
	</p>
