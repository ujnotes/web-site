	<h3>What is a laser?</h3>
	<p>
		A laser is a device that produces light through <strong>light amplification by stimulated emission of radiation</strong>.
	</p>
	<p>
		Its output is typically narrow in direction, concentrated in frequency, and strongly related in phase. These properties distinguish laser light from ordinary thermal or fluorescent light.
	</p>
	<h3>How does it work?</h3>
	<p>
		A laser has three essential parts:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>An active medium</strong> whose atoms, ions, molecules or semiconductor states can emit light</div></li>
		<li><div><strong>A pumping mechanism</strong> that supplies energy and creates a population inversion</div></li>
		<li><div><strong>An optical resonator</strong> that reflects light through the medium so stimulated emission grows</div></li>
	</ul>
	<p>
		An excited system can emit a photon spontaneously. A matching photon can also stimulate another excited particle to emit a second photon with related frequency, direction and phase.
	</p>
	<h3>Why are lasers important?</h3>
	<p>
		Lasers enable optical fiber communication, barcode scanners, surgery, manufacturing, surveying, spectroscopy, microscopy, data storage, displays, printers, measurement and scientific experiments.
	</p>
	<p>
		Their precision lets people cut, measure, communicate and manipulate matter with extraordinary control.
	</p>
	<h3>A short history</h3>
	<p>
		The maser demonstrated stimulated emission with microwaves. The first working optical laser was built in 1960. Since then, gas, solid-state, dye, fiber, semiconductor and ultrafast lasers have been developed for different wavelengths, powers and pulse durations.
	</p>
	<h3>Limits and risks</h3>
	<p>
		Lasers are not automatically efficient or safe. They can damage eyes and skin, heat materials, create hazardous reflections and require careful control of power and wavelength.
	</p>
	<p>
		Real devices have noise, divergence, limited lifetime, thermal constraints and imperfect coherence.
	</p>
	<h3>Future impact</h3>
	<p>
		Lasers will support faster optical networks, precision manufacturing, medical treatment, autonomous sensing, astronomy, quantum technologies and experiments on extreme states of matter.
	</p>
	<p>
		Their deeper importance is that quantum behavior can be turned into a reliable engineering tool: controlled light becomes a way to carry information, measure the world and change it.
