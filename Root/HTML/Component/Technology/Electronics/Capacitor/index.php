	<h3>What is a capacitor?</h3>
	<p>
		A capacitor stores energy in an electric field between conductors.
	</p>
	<p>
		Its capacitance measures how much charge is stored for a given voltage: <strong>C = Q/V</strong>.
	</p>
	<h3>How does it behave?</h3>
	<p>
		A capacitor resists sudden changes in voltage. Current depends on how quickly voltage changes: <strong>I = C dV/dt</strong>.
	</p>
	<p>
		It passes changing signals more readily than steady DC and can combine with resistors or inductors to set timing and frequency.
	</p>
	<h3>Uses</h3>
	<p>
		Capacitors smooth rectified power, decouple integrated circuits, filter signals, couple amplifier stages, tune resonant circuits and store short bursts of energy.
	</p>
	<p>
		Real capacitors have leakage, equivalent series resistance, voltage limits, tolerance and sometimes polarity.
	</p>
	<h3>History and future</h3>
	<p>
		Early capacitors supported experiments in electrostatics and radio. Ceramic, film, electrolytic and supercapacitor technologies now serve different ranges of energy, voltage and lifetime.
	</p>
	<p>
		Future storage will improve through new dielectrics and materials, but batteries remain better for many long-duration applications.
