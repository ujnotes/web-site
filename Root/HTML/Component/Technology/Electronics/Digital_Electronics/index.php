	<p>
		Relay logic and vacuum-tube computers preceded transistor logic. Integrated circuits, semiconductor memory and microprocessors made digital systems smaller and cheaper. Personal computers, mobile devices and cloud services extended the idea across society.
	</p>
	<h3>Limits and future</h3>
	<p>
		Digital systems still depend on analog interfaces, power, timing and physical media. They can fail through noise, bugs, security weaknesses or incorrect assumptions.
