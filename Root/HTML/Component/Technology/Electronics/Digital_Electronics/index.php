	<p>
		Transistors form logic gates such as NOT, AND and OR. Gates combine into adders, selectors, registers, memories and processors.
	</p>
	<p>
		A clock can coordinate changes. A digital system may also be asynchronous, responding directly to events rather than a shared clock.
	</p>
	<p>
		Digital design has two layers: hardware determines physical behavior, while architecture and software determine how the behavior is used.
	</p>
	<h3>Why is it powerful?</h3>
	<p>
		Discrete representation makes copying, storage, error checking and programmable transformation practical.
	</p>
	<p>
		The same underlying circuits can handle text, images, music, measurements and instructions because all can be encoded as patterns of bits.
	</p>
