	<h3>What does it do?</h3>
	<p>
		A diode can rectify alternating current, protect against reversed polarity, clamp a voltage, detect a radio signal, emit light or convert light into current.
	</p>
	<p>
		Forward bias allows substantial current after a characteristic threshold. Reverse bias blocks current until leakage or breakdown becomes important.
	</p>
	<h3>Why is it important?</h3>
	<p>
		Diodes are simple, fast and robust building blocks. Rectifiers make DC supplies from AC. Zener and avalanche behavior provide references and protection. LEDs made efficient solid-state lighting practical.
	</p>
	<h3>Limits and future</h3>
	<p>
		A diode is not a perfect switch. It has forward drop, capacitance, recovery time, leakage and heat.
