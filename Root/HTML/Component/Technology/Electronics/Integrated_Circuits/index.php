	<h3>What is an integrated circuit?</h3>
	<p>
		An integrated circuit, or IC, is a manufactured piece of semiconductor containing transistors, connections and often capacitors, resistors or other structures.
	</p>
	<p>
		Instead of assembling each component separately, fabrication creates many devices together and connects them on one die.
	</p>
	<h3>Why was this a breakthrough?</h3>
	<p>
		An IC makes a system smaller, faster, cheaper and more reliable. Short connections reduce delay and unwanted electrical effects. Manufacturing the same pattern repeatedly also makes complex designs reproducible.
	</p>
	<p>
		ICs are the foundation of memory, processors, sensors, radios, power controllers and nearly every modern digital product.
	</p>
	<h3>How is an IC made?</h3>
	<p>
		Engineers design layers of patterns. A wafer is coated, exposed through photolithography, etched, doped and covered with new materials many times.
	</p>
	<p>
		After testing, the wafer is cut into dies and each die is packaged so it can connect to a circuit board.
	</p>
	<p>
		The result depends on chemistry, optics, mechanical precision, software, testing and a global supply chain.
	</p>
	<h3>History and future</h3>
	<p>
		The first practical integrated circuits appeared in the late 1950s. Improvements in manufacturing placed more transistors on each chip and made microprocessors possible.
	</p>
	<p>
		The future will combine smaller structures with three-dimensional packaging, specialized accelerators, photonic links and new materials.
	</p>
	<p>
		Limits include heat, fabrication cost, defects, energy use, e-waste and concentration of manufacturing capability. More transistors are valuable only when they produce useful, trustworthy and accessible systems.
	</p>
