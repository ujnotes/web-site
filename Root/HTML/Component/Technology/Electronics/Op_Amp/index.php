	<h3>What is an operational amplifier?</h3>
	<p>
		An operational amplifier, or op amp, is a high-gain differential amplifier with two inputs and an output.
	</p>
	<p>
		It responds mainly to the difference between its non-inverting and inverting inputs. External components and negative feedback determine the useful behavior.
	</p>
	<h3>Why is it powerful?</h3>
	<p>
		With resistors, capacitors and diodes, an op amp can add, subtract, integrate, differentiate, filter, compare, regulate and condition signals.
	</p>
	<p>
		The same basic device can serve as an audio stage, sensor interface, oscillator, voltage reference or control loop.
	</p>
	<h3>The ideal model</h3>
	<p>
		An ideal op amp has infinite open-loop gain, infinite input resistance, zero output resistance and unlimited bandwidth. Real devices have finite gain, noise, offset voltage, bias current, limited slew rate and a restricted supply range.
	</p>
	<p>
		Negative feedback makes the circuit predictable, but stability must be checked.
	</p>
	<h3>History and future</h3>
	<p>
		Op amps began as valve and transistor circuits used in analog computers. Integrated op amps made precision analog design accessible.
	</p>
	<p>
		Future devices will combine lower power, wider bandwidth, better sensing and digital calibration. The central lesson is that feedback turns a raw active device into a controlled function.
