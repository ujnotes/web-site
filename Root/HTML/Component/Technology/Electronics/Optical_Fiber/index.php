	<h3>What is optical fiber?</h3>
	<p>
		Optical fiber is a thin strand of glass or plastic that guides light. Information is encoded into changes in the light and carried over long distances with low loss.
	</p>
	<p>
		A fiber has a core, cladding and protective layers. Total internal reflection and carefully engineered refractive indices keep much of the light inside the core.
	</p>
	<h3>Why is it important?</h3>
	<p>
		Fiber offers high bandwidth, low attenuation and resistance to electromagnetic interference.
	</p>
	<p>
		It carries internet traffic, telephone calls, video, cloud services, scientific data and signals between mobile networks. A single cable can carry many wavelengths at once.
	</p>
	<h3>How does it work?</h3>
	<p>
		A laser or light-emitting device sends pulses into the fiber. A photodetector converts arriving light back into an electrical signal. Repeaters or optical amplifiers restore the signal on very long routes.
	</p>
	<p>
		Wavelength-division multiplexing lets several optical channels share one fiber. The speed of a network also depends on switches, protocols, endpoints and maintenance—not only on the glass.
	</p>
	<h3>History</h3>
	<p>
		Experiments in guided light preceded practical low-loss fiber. Improved glass purification and semiconductor lasers made fiber communication commercially useful in the late twentieth century. Submarine cables then connected continents with enormous capacity.
	</p>
	<h3>Future impact</h3>
	<p>
		Fiber will support data centers, scientific instruments, remote work, telemedicine and increasingly distributed computing.
	</p>
	<p>
		The challenges include construction cost, physical security, repair after damage, unequal access and the energy used by equipment at each end. Fiber expands communication, but social benefit still depends on affordable and open networks.
