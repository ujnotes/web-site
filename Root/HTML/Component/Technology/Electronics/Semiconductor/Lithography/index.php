	<h3>What is semiconductor lithography?</h3>
	<p>
		Lithography is the process of transferring a pattern onto a semiconductor wafer.
	</p>
	<p>
		In photolithography, a wafer is coated with photoresist, exposed through a mask or reticle, developed and then etched or otherwise processed.
	</p>
	<h3>Why is it important?</h3>
	<p>
		Lithography defines the size, shape and alignment of features that become transistors, wires, contacts and other structures.
	</p>
	<p>
		Smaller and more accurately aligned patterns can increase density and improve performance, but only when materials, optics, defects and heat remain controllable.
	</p>
	<h3>A short history</h3>
	<p>
		Early integrated circuits used relatively large features and optical methods. Repeated improvements in resists, lenses, alignment and process control enabled modern chips.
	</p>
	<p>
		Deep ultraviolet and extreme ultraviolet systems extend the usable resolution of optical projection.
	</p>
	<h3>Limits and future</h3>
	<p>
		Lithography is constrained by wavelength, optics, focus, vibration, defects, cost and materials. It is one part of a much larger manufacturing sequence.
	</p>
	<p>
		The field is strategically important because a small number of specialized tools and suppliers support much of advanced chip production.
	</p>
