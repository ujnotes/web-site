	<h3>What is a semiconductor?</h3>
	<p>
		A semiconductor is a material whose ability to conduct electricity can be controlled.
	</p>
	<p>
		Silicon is the best-known example. Its conductivity changes with temperature, light, electric fields and carefully introduced impurities called dopants.
	</p>
	<h3>Why does it matter?</h3>
	<p>
		Semiconductors allow engineers to make rectifiers, sensors, transistors, memory and integrated circuits.
	</p>
	<p>
		They occupy the middle ground between conductors and insulators: conductive enough to carry charge, but controllable enough to make a decision or amplify a signal.
	</p>
	<h3>Junctions and devices</h3>
	<p>
		Adding different dopants creates p-type and n-type regions. Their boundary forms a junction with useful electrical behavior.
	</p>
	<p>
		Diodes use junctions to control direction. Transistors use multiple regions or a field-controlled channel. Light-emitting diodes, solar cells and photodetectors convert between electricity and light.
	</p>
	<h3>History</h3>
	<p>
		The discovery of semiconductor behavior led from crystal detectors to the transistor and integrated circuit. Manufacturing has since become a global discipline involving chemistry, optics, precision machinery, software and enormous clean-room facilities.
	</p>
	<h3>Future</h3>
	<p>
		New materials such as gallium nitride, silicon carbide and two-dimensional crystals may improve high-power, high-frequency or flexible devices.
	</p>
	<p>
		The field faces limits in heat, defects, fabrication cost, critical materials and geopolitical concentration. Semiconductor capability is now both an engineering resource and a strategic social dependency.
