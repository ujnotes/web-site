	<p>
		A system creates, transforms, transmits and interprets signals.
	</p>
	<p>
		Important ideas include amplitude, frequency, phase, bandwidth, sampling, noise, distortion, interference and signal-to-noise ratio.
	</p>
	<p>
		Analog signals vary continuously. Digital signals use symbols and codes. Neither is automatically better: the choice depends on the source, channel, required accuracy, cost and error tolerance.
	</p>
	<h3>Why is it important?</h3>
	<p>
		Almost every information technology depends on signal processing. Sensors turn physical events into signals. Filters remove unwanted components. Modulators adapt signals to a channel. Detectors and decoders recover meaning.
	</p>
	<p>
		Understanding signals lets engineers predict what survives a cable, an antenna, an optical fiber or a computer interface.
	</p>
	<h3>History and future</h3>
	<p>
		Telegraphy, telephony and radio created practical signal theory. Fourier analysis, feedback and information theory then gave engineers powerful mathematical tools.
