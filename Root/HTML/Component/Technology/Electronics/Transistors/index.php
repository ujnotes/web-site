	</p>
	<h3>Why is it so important?</h3>
	<p>
		Transistors are small, fast, efficient and manufacturable in enormous numbers. A single device can implement a decision; billions together can form memory, processors, radio circuits and power controllers.
	</p>
	<p>
		This is the physical foundation of modern computing and communications.
	</p>
	<h3>Main families</h3>
	<p>
		A bipolar junction transistor uses carriers crossing junctions and is useful for amplification and switching. A field-effect transistor controls a channel with an electric field. MOSFETs dominate much digital logic and many power converters.
	</p>
	<p>
		The transistor is not “a one” or “a zero” by itself. Digital circuits use transistor arrangements to create stable logic states.
