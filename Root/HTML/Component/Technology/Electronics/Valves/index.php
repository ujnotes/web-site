	<p>
		An electronic valve, also called a vacuum tube, controls the flow of electrons through a vacuum or low-pressure gas.
	</p>
	<p>
		A heated cathode emits electrons. Electric fields at grids and electrodes control that flow, allowing amplification, switching, rectification or oscillation.
	</p>
	<h3>Why was it powerful?</h3>
	<p>
		A valve could make a weak signal strong enough to drive a speaker, a transmitter or another circuit. Multiple valves could perform logic and calculation.
	</p>
	<p>
		This made long-distance telephony, radio broadcasting, radar and early electronic computers possible.
	</p>
	<h3>History</h3>
	<p>
		The diode valve grew from experiments with thermionic emission. The triode added a control grid and became a practical amplifier. Valve technology dominated the first half of the twentieth century before transistors offered smaller size, lower power and greater reliability.
	</p>
	<h3>Strengths and limits</h3>
	<p>
		Valves can tolerate high voltages, produce useful high-power radio signals and create distinctive audio behavior. They are large, fragile, hot and slow to start. Their heaters consume power and their operating life is finite.
	</p>
	<h3>Why study them now?</h3>
	<p>
		Valves explain the physical idea of controlled amplification and the transition from electromechanical to solid-state technology. They still appear in specialist transmitters, scientific instruments and some audio equipment.
	</p>
