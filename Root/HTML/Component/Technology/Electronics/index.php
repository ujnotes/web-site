		Electrical engineering asks how energy and fields behave broadly. Electronics focuses on devices that switch, amplify, filter, store and interpret changing electrical quantities.
	</p>
	<h3>Why is it powerful?</h3>
	<p>
		A small voltage can control a much larger current. A circuit can distinguish a signal from noise, remember a state, calculate a result or translate information into light and sound.
