		<li><div><strong>DC to DC</strong> changes voltage while preserving direct-current operation.</div></li>
		<li><div><strong>AC to AC</strong> changes voltage or frequency for motors and grids.</div></li>
	</ul>
	<p>
		A converter rapidly switches devices such as MOSFETs or insulated-gate bipolar transistors. Filtering and control turn those switched states into a useful output.
	</p>
	<h3>Why does it matter?</h3>
	<p>
		Power electronics improves efficiency and control. It lets a motor accelerate smoothly, a charger protect a battery, a solar array match changing sunlight to a grid and a data center regulate thousands of processors.
	</p>
	<p>
		A small improvement in conversion efficiency can save enormous energy when a system operates continuously or is deployed millions of times.
	</p>
	<h3>History</h3>
	<p>
		Early power conversion relied on mechanical switches, transformers and mercury-arc devices. Silicon diodes and thyristors made solid-state control practical. Modern wide-bandgap materials such as silicon carbide and gallium nitride can switch faster and operate at higher temperature.
	</p>
	<h3>Future impact</h3>
	<p>
