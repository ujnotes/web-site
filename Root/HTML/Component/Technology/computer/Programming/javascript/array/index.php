	<pre class='indent-c'><code class='block'>&lt;array&gt;.splice(&lt;index:&gt;, &lt;count&gt;</code></pre>
	<p>
		Acts in-place.
	</p>
	<p>
		Returns spliced : beginning from index - count elements.
	</p>
	<h2>E.g.</h2>
	<p>
		X = [1,2,3].
	</p>
	<p>
		X.splice(1, 2);.
	</p>
	<p>
		X := 1.
	</p>
	<p>
		Return := [2,3].
	</p>
