<h2 class='center'><?php echo $desc; ?></h2>
<div id='message'>
		<h3>What is a decision?</h3>
	<p>
		A decision is the selection of one course of action from more than one possibility.
	</p>
	<p>
		It connects thought with action.
	</p>
	<p>
		You may believe that rain is likely, value staying dry and know that an umbrella is available. The decision is the point at which this information becomes: <em>carry the umbrella</em>.
	</p>
	<p>
		A decision does not need certainty. It needs a choice made with the information, values and time available.
	</p>
	<h3>Is every action a decision?</h3>
	<p>
		No.
	</p>
	<p>
		Some actions are reflexes, habits or automatic adjustments. The hand withdraws from a hot surface before a deliberate choice is completed. The body keeps balance without asking which muscle to move.
	</p>
	<p>
		Decisions appear when alternatives are represented and one is selected.
	</p>
	<p>
		Even then, much of the work may remain unconscious. A choice can feel sudden because <a class="content-link XURL" href="/world/philosophy/cognition" data-target="world/philosophy/cognition" data-title="cognition">cognition</a> has compared possibilities before the result enters awareness.
	</p>
	<h3>What does a decision require?</h3>
	<p>
		A decision usually depends upon:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Possible actions</strong> — what can be done</div></li>
		<li><div><strong>A model</strong> — what may follow from each action</div></li>
		<li><div><strong>Values or goals</strong> — which outcomes matter</div></li>
		<li><div><strong>Evidence</strong> — what is known about the present situation</div></li>
		<li><div><strong>Constraints</strong> — limits of time, ability, rules or resources</div></li>
	</ul>
	<p>
		Remove any one of these and the decision changes.
	</p>
	<p>
		A good option that cannot actually be carried out is not a useful option.
	</p>
	<h3>How do predictions guide choice?</h3>
	<p>
		To choose is to compare possible futures.
	</p>
	<p>
		If I leave now, I may arrive on time. If I wait, I may avoid the rain but miss the train.
	</p>
	<p>
		A <a class="content-link XURL" href="/world/philosophy/model" data-target="world/philosophy/model" data-title="model">model</a> connects each action with expected consequences. <a class="content-link XURL" href="/world/philosophy/inference" data-target="world/philosophy/inference" data-title="Inference">Inference</a> estimates which consequences are likely.
	</p>
	<p>
		The decision then depends upon both likelihood and value. A small chance of severe harm may matter more than a large chance of mild inconvenience.
	</p>
	<h3>Why are decisions difficult?</h3>
	<p>
		The future is uncertain, goals can conflict and information has a cost.
	</p>
	<p>
		A doctor may want the most accurate diagnosis while also avoiding a risky test. A family may want a safer home but need to remain near work. A public policy may benefit many people while placing a heavy burden on a few.
	</p>
	<p>
		Difficulty does not always mean the thinker is confused. Sometimes the world contains a real conflict between things worth protecting.
	</p>
	<h3>What is a trade-off?</h3>
	<p>
		A trade-off occurs when gaining more of one valued outcome requires giving up some of another.
	</p>
	<p>
		Money spent today cannot also be saved for tomorrow. A faster route may be less safe. A more accurate model may require more time and energy.
	</p>
	<p>
		Naming the trade-off makes the decision clearer.
	</p>
	<p>
		Without doing so, people often argue as if one option has benefits while the other has only costs.
	</p>
	<h3>What is risk?</h3>
	<p>
		Risk concerns outcomes that are uncertain and harmful.
	</p>
	<p>
		It depends upon both the chance of harm and its severity.
	</p>
	<p>
		Crossing an empty road has a small risk. Crossing while a fast vehicle approaches has a much larger one. A rare event can still deserve attention when its consequence is catastrophic.
	</p>
	<p>
		Uncertainty cannot always be removed. A sensible decision manages it by seeking evidence, keeping margins of safety and preparing for failure.
	</p>
	<h3>What is the value of more information?</h3>
	<p>
		More <a class="content-link XURL" href="/world/philosophy/information" data-target="world/philosophy/information" data-title="information">information</a> is valuable when it can change the choice enough to justify the time or cost of obtaining it.
	</p>
	<p>
		Checking the weather before a journey is cheap and may change what you carry. Delaying urgent treatment for a small improvement in certainty may cause greater harm than acting now.
	</p>
	<p>
		A decision-maker must sometimes decide whether to keep investigating or stop and act.
	</p>
	<p>
		Perfect information usually arrives too late, if it arrives at all.
	</p>
	<h3>What are heuristics?</h3>
	<p>
		Heuristics are simple rules that make decisions faster.
	</p>
	<p>
		“Keep a safe distance from the vehicle ahead” does not calculate every physical variable, but it works well across many ordinary situations.
	</p>
	<p>
		Such shortcuts are necessary because time and attention are limited.
	</p>
	<p>
		They can also fail. A rule learnt in one setting may not fit another. The important skill is knowing when a quick rule is enough and when careful analysis is needed.
	</p>
	<h3>How do emotions affect decisions?</h3>
	<p>
		Emotion gives outcomes urgency and value.
	</p>
	<p>
		Fear warns of danger. Compassion makes another person's suffering matter. Regret helps us imagine how a choice may later feel.
	</p>
	<p>
		A person without emotion would not become perfectly rational. They might struggle to decide because facts alone do not say what is worth choosing.
	</p>
	<p>
		But emotion can also distort estimates. Fear may make a vivid danger seem common, while familiarity makes a serious risk seem harmless.
	</p>
	<p>
		Reason should examine emotion, not attempt to live without it.
	</p>
	<h3>What is a good decision?</h3>
	<p>
		A good decision uses the available evidence honestly, considers relevant outcomes and respects the values that ought to matter.
	</p>
	<p>
		It should not be judged only by what happened.
	</p>
	<p>
		A careful decision can lead to a bad outcome because the world is uncertain. A reckless decision can succeed through luck.
	</p>
	<p>
		The better question is whether the method deserved confidence at the time.
	</p>
	<p>
		Outcomes still matter because they provide feedback. But one outcome is not always enough to judge the quality of the choice.
	</p>
	<h3>Who is responsible for a decision made by a machine?</h3>
	<p>
		Responsibility remains with the people and institutions that design, deploy and benefit from the system.
	</p>
	<p>
		A machine may rank applicants, recommend treatment or control a vehicle. Its output results from a <a class="content-link XURL" href="/world/philosophy/program" data-target="world/philosophy/program" data-title="program">program</a>, a model, training data, chosen goals and rules about how the output is used.
	</p>
	<p>
		Calling the result “the computer's decision” can hide these human choices.
	</p>
	<p>
		The more serious the consequence, the more important it is to know who can examine, override and answer for the system.
	</p>
	<h3>Does intelligence guarantee good decisions?</h3>
	<p>
		No.
	</p>
	<p>
		<a class="content-link XURL" href="/world/philosophy/intelligence" data-target="world/philosophy/intelligence" data-title="Intelligence">Intelligence</a> can improve prediction and reveal effective actions. It does not decide which goals are morally right.
	</p>
	<p>
		A highly intelligent person can choose selfishly. An efficient system can optimize a harmful objective.
	</p>
	<p>
		Good decisions require more than ability. They require sound values, concern for those affected and willingness to correct error.
	</p>
	<h3>So what is a decision, finally?</h3>
	<p>
		A decision is where information, prediction and value become action.
	</p>
	<p>
		It is made under limits: incomplete knowledge, finite time and competing aims.
	</p>
	<p>
		Good decision-making does not wait for impossible certainty. It makes uncertainty visible, compares consequences fairly, protects against serious harm and learns from what follows.
	</p>
	<p>
		A choice shapes the world. It also reveals what the chooser values.
	</p>

</div>

