<div id='message'>
		<h3>What is learning?</h3>
	<p>
		Learning is a lasting change produced by experience.
	</p>
	<p>
		The change may appear in knowledge, skill, expectation or behaviour. A child learns a word. A driver learns to judge a narrow turn. A body learns to react more quickly to a familiar threat.
	</p>
	<p>
		A temporary change caused by tiredness or mood is not usually learning.
	</p>
	<p>
		Learning occurs when experience changes what a system can do next.
	</p>
	<h3>Is learning the same as memory?</h3>
	<p>
		No, though they depend upon one another.
	</p>
	<p>
		Memory preserves information so that the past can affect the present. Learning is the process by which experience changes what is preserved and how it is used.
	</p>
	<p>
		One can remember a telephone number briefly without learning anything general. One can also learn a motor skill without being able to describe every experience that shaped it.
	</p>
	<p>
		Memory keeps traces. Learning reorganizes them into future ability.
	</p>
	<h3>How does learning begin?</h3>
	<p>
		Learning begins when a system detects a relationship.
	</p>
	<p>
		A baby hears a repeated sound while seeing the same person. A dog notices that a particular sound is followed by food. A student discovers that dividing both sides of an equation preserves equality.
	</p>
	<p>
		Repeated events alone are not enough. The learner must notice which events belong together.
	</p>
	<p>
		Attention, timing and earlier knowledge all influence what is learnt.
	</p>
	<h3>What role does error play?</h3>
	<p>
		Error reveals a difference between expectation and reality.
	</p>
	<p>
		Suppose you expect a door to open when pushed, but it does not. The failure directs attention towards the handle, the lock or the possibility that the door opens the other way.
	</p>
	<p>
		A learner uses such differences to correct a <a class="content-link XURL" href="/world/philosophy/model" data-target="world/philosophy/model" data-title="model">model</a>.
	</p>
	<p>
		Without an expectation, an event may merely happen. With an expectation, surprise becomes information about what needs to change.
	</p>
	<h3>Does learning require repetition?</h3>
	<p>
		Often, but not always.
	</p>
	<p>
		Repetition strengthens a relationship and shows whether it remains stable across occasions. Practice also makes some operations faster and less demanding of attention.
	</p>
	<p>
		But a single event can be enough when its consequence is strong. Touching a hot surface once may teach a lasting lesson.
	</p>
	<p>
		What matters is not repetition alone. It is how strongly the experience changes the model, memory or value attached to an action.
	</p>
	<h3>What is practice?</h3>
	<p>
		Practice is repeated action aimed at improving performance.
	</p>
	<p>
		Useful practice contains feedback. A musician hears whether the note is correct. A bowler sees where the ball lands. A programmer observes whether the program behaves as intended.
	</p>
	<p>
		Repeating the same mistake without noticing it can strengthen the mistake.
	</p>
	<p>
		Good practice keeps the task difficult enough to reveal error, but clear enough for the learner to correct it.
	</p>
	<h3>What is understanding?</h3>
	<p>
		Understanding is learning the relationships that make knowledge transferable.
	</p>
	<p>
		A student may memorize that a particular answer is 24. Understanding appears when the student can explain why and use the same principle in a new problem.
	</p>
	<p>
		Memorization preserves an answer. Understanding builds a model that can produce answers.
	</p>
	<p>
		Both have value. Facts must sometimes be remembered, but disconnected facts are difficult to use when the question changes.
	</p>
	<h3>What is generalization?</h3>
	<p>
		Generalization is the ability to apply what was learnt to a new case.
	</p>
	<p>
		A child who learns the idea of a chair can recognize a chair never seen before. The child does not compare the object with a perfect stored picture. A broader pattern has been learnt.
	</p>
	<p>
		Generalization requires ignoring some differences while preserving important ones.
	</p>
	<p>
		Too little generalization makes every case seem unrelated. Too much treats important differences as if they did not matter.
	</p>
	<h3>Can we learn the wrong thing?</h3>
	<p>
		Yes.
	</p>
	<p>
		Experience does not explain itself.
	</p>
	<p>
		A person who becomes ill after eating one food may blame that food even when the cause was elsewhere. A child praised only for quick answers may learn that appearing certain matters more than thinking carefully.
	</p>
	<p>
		Bias, coincidence and poor feedback can all produce mistaken learning.
	</p>
	<p>
		What is learnt should therefore be tested against new cases and, when possible, compared with stronger evidence.
	</p>
	<h3>How do emotions affect learning?</h3>
	<p>
		Emotion assigns importance.
	</p>
	<p>
		Fear can make a danger memorable. Curiosity can hold attention on a difficult question. Pleasure can strengthen an action that led to reward.
	</p>
	<p>
		This is useful because a living system cannot remember every detail equally.
	</p>
	<p>
		But emotional strength is not proof of truth. A vivid story may be remembered more easily than a quiet fact. Good learning respects emotion while checking the model it creates.
	</p>
	<h3>How do machines learn?</h3>
	<p>
		A machine-learning system changes an internal model using examples or feedback.
	</p>
	<p>
		It may be shown correct answers, discover patterns without labels, or learn which actions lead to reward.
	</p>
	<p>
		An <a class="content-link XURL" href="/world/philosophy/algorithm" data-target="world/philosophy/algorithm" data-title="algorithm">algorithm</a> determines how the model changes. Training data supplies experience. A measure of error or reward guides adjustment.
	</p>
	<p>
		The system has learnt when this adjustment improves its behaviour on relevant new cases, not merely when it remembers its training examples.
	</p>
	<h3>Is machine learning like human learning?</h3>
	<p>
		In some respects.
	</p>
	<p>
		Both can detect patterns, change through feedback and generalize beyond earlier examples.
	</p>
	<p>
		But human learning is shaped by a living body, needs, emotion, social relationships, language and conscious experience. Present machine-learning systems are built and trained for more limited purposes, even when their outputs cover many subjects.
	</p>
	<p>
		Similar performance does not prove an identical process.
	</p>
	<h3>Does learning guarantee improvement?</h3>
	<p>
		No.
	</p>
	<p>
		Learning means change through experience, not necessarily change towards truth or goodness.
	</p>
	<p>
		A system can learn a prejudice, a harmful habit or a successful deception. It can optimize the wrong measure.
	</p>
	<p>
		Improvement requires a standard: more accurate prediction, greater skill, reduced harm or some other valued result.
	</p>
	<p>
		The quality of learning depends upon the experience, the feedback and the goal.
	</p>
	<h3>How does learning support intelligence?</h3>
	<p>
		<a class="content-link XURL" href="/world/philosophy/intelligence" data-target="world/philosophy/intelligence" data-title="Intelligence">Intelligence</a> cannot remain effective in a changing world without learning.
	</p>
	<p>
		Learning corrects models, adds skills and changes expectations. <a class="content-link XURL" href="/world/philosophy/inference" data-target="world/philosophy/inference" data-title="Inference">Inference</a> uses what has been learnt to reach new conclusions. Decision uses those conclusions to select action.
	</p>
	<p>
		The action creates another experience, and the cycle continues.
	</p>
	<p>
		An intelligent system is not one that never fails. It is one that can use failure to become less wrong.
	</p>
	<h3>So what is learning, finally?</h3>
	<p>
		Learning is how experience changes future possibility.
	</p>
	<p>
		It preserves useful information, corrects models, strengthens skills and allows old lessons to guide new situations.
	</p>
	<p>
		But experience can also teach badly. Learning becomes reliable when feedback is honest, errors can be examined and conclusions are tested beyond the examples that formed them.
	</p>
	<p>
		To learn well is not merely to change. It is to change in closer contact with reality.
	</p>

</div>

