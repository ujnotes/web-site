		<li><div><strong>डिजिटल मनी (Digital Money)</strong> — इलेक्ट्रॉनिक बहीखाते, तत्काल भुगतान नेटवर्क (UPI) और केंद्रीय बैंक डिजिटल मुद्राएँ।</div></li>
		<li><div><strong>मुद्रास्फीति (Inflation)</strong> — सामान्य मूल्य स्तर में वृद्धि किस प्रकार मुद्रा की क्रय शक्ति को घटाती है।</div></li>
		<li><div><strong>विनिमय दर (Exchange Rate)</strong> — विभिन्न देशों की मुद्राओं का सापेक्ष मूल्य और विदेशी मुद्रा बाज़ार की ताकतें।</div></li>
	</ul>
