	<h3>मुद्रा के तीन प्रमुख कार्य</h3>
	<ul class="list-bullet content-list">
		<li><div><strong>विनिमय का माध्यम (Medium of Exchange)</strong> — यह व्यापार में हर किसी द्वारा स्वीकार्य होकर आवश्यकताओं के दोहरे संयोग की समस्या को समाप्त करता है।</div></li>
		<li><div><strong>लेखा की इकाई (Unit of Account)</strong> — यह एक सामान्य पैमाना प्रदान करता है ताकि पूरी तरह से अलग वस्तुओं के मूल्य की सीधी तुलना की जा सके।</div></li>
		<li><div><strong>मूल्य का संचय (Store of Value)</strong> — यह लोगों को आज अर्जित क्रय शक्ति को बचाने और उसे महीनों या वर्षों बाद उपयोग करने की सुविधा देता है।</div></li>
	</ul>
