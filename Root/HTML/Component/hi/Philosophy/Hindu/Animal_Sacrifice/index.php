		<h3>पशु बलि क्या है?</h3>
	<p>
		पशु बलि किसी देवता या देवी को किसी पशु के जीवन का औपचारिक अनुष्ठानिक समर्पण है। हिन्दू परंपराओं में, विशेषकर शाक्त साधना में, यह अंधाधुंध संहार या क्रूरता का कृत्य नहीं है। यह जगन्माता के सम्मुख—विशेष रूप से दुर्गा पूजा या काली पूजा के दौरान—किया जाने वाला एक प्रतिष्ठित अनुष्ठान है, जहाँ अर्पित जीव का रक्त और जीवन देवी को समर्पित किया जाता है और मांस प्रसाद के रूप में वितरित किया जाता है।
	</p>
	<p>
		कई आधुनिक विचारकों के लिए यह प्रथा विचलित करने वाली लग सकती है। लगभग सात वर्ष पहले मेरी भी यही सोच थी। मैं मंदिरों में पशु बलि रोकने के लिए याचिकाओं पर हस्ताक्षर एकत्र कर रहा था। मैं इसे आधुनिक शहरी संवेदनाओं के चश्मे से देख रहा था: निर्दोष जीवों पर थोपी गई अनावश्यक हिंसा।
	</p>
	<p>
		लेकिन वर्षों बाद, एक कट्टर शाकाहारी होने के बावजूद, मैं दुर्गा पूजा के दौरान बलि प्रांगण में उतरा और व्यक्तिगत रूप से दस बकरों की बलि दी।
	</p>
	<p>
		मैंने यह किसी अहंकार या दिखावे के लिए नहीं किया। वर्षों के अध्ययन और चिंतन के बाद मुझे यह उस दर्शन का एक तार्किक और अनिवार्य निष्कर्ष लगा, जो अस्तित्व के कठोर सत्यों से मुँह नहीं मोड़ता।
	</p>
	<h3>प्रतीकात्मक व्याख्या</h3>
	<p>
		बलि की सबसे आम आधुनिक आलोचना यह है कि यह मूल रूप से प्रतीकात्मक थी और बाद में विकृत हो गई।
	</p>
	<p>
		एक प्रमुख तर्क—जो प्रायः 'द लॉ ऑफ़ वन' (रा सामग्री) जैसे आधुनिक आध्यात्मिक विचारों या वेदांत के लाक्षणिक अर्थों से प्रभावित है—यह प्रस्ताव करता है कि:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>पशु आंतरिक विकारों का प्रतीक है</strong>: बकरा या भैंसा हमारी पाशविक प्रवृत्तियों—काम, क्रोध, लोभ, अहंकार और अनियंत्रित भूख का प्रतिनिधित्व करता है। पशु की "बलि" देने का अर्थ अपने भीतर की इन दुर्बलताओं को समाप्त करना है।</div></li>
		<li><div><strong>उच्च चेतना हिंसा को अस्वीकार करती है</strong>: यह माना जाता है कि आध्यात्मिक रूप से उन्नत चेतना अनिवार्य रूप से करुणावान होती है। अतः कोई ईश्वरीय निर्देश किसी निर्दोष जीव की हत्या का आदेश नहीं दे सकता।</div></li>
		<li><div><strong>अनुष्ठान एक विकृति है</strong>: इस दृष्टिकोण के अनुसार, भौतिक रक्त बलि तब शुरू हुई जब अपरिपक्व चेतना वाले मनुष्यों ने आंतरिक आध्यात्मिक रूपक को बाहरी भौतिक निर्देश समझ लिया, या वे निम्न-घनत्व वाली नकारात्मक शक्तियों द्वारा भ्रमित हो गए।</div></li>
	</ul>
	<p>
		यह व्याख्या सुनने में बहुत सहज और सुखद लगती है। यह उस आधुनिक आध्यात्मिक सांचे में पूरी तरह फिट बैठती है जहाँ आध्यात्मिक प्रगति का अर्थ केवल कोमल अहिंसा माना जाता है।
	</p>
	<p>
		किन्तु यह दृष्टिकोण अनुष्ठान के इतिहास और उसके दर्शन दोनों को गलत समझता है।
	</p>
	<h3>अद्वैत का सत्य और अस्तित्व की अनिवार्यता</h3>
	<p>
		अद्वैत वेदांत सिखाता है कि समस्त अस्तित्व एक है: ब्रह्म। परम स्तर पर स्वयं, पशु, वृक्ष और पाषाण के बीच कोई मूलभूत अलगाव नहीं है। मैं इस जुड़ाव को गहराई से अनुभव करता हूँ।
	</p>
	<p>
		परंतु हम केवल अव्यक्त परम सत्य में नहीं रहते; हम भौतिक जगत में जीते हैं। इस भौतिक धरातल पर जीवन की एक अपरिहार्य शर्त है: <strong>जीवन केवल दूसरे जीवन का उपभोग करके ही टिका रह सकता है</strong>।
	</p>
	<p>
		आत्महत्या कोई नैतिक समाधान नहीं है। एक भौतिक शरीर में बने रहने का अर्थ है कि जब आप सांस लेते हैं तो सूक्ष्मजीव मरते हैं, जब आप भोजन करते हैं तो वनस्पतियां नष्ट होती हैं, और जब आप आश्रय बनाते हैं तो कई जीवों का आवास उजड़ता है। एक शाकाहारी होने पर भी मेरे जीवित रहने के लिए अन्य जीवों का अंत अपरिहार्य है।
	</p>
	<p>
		यदि कोई अद्वैत के आधार पर यह तर्क दे कि किसी भी जीवन का अंत नहीं होना चाहिए, तो उसे यह समझाना होगा कि वनस्पति का जीवन लेना स्वीकार्य और पशु का जीवन लेना अस्वीकार्य क्यों है। दोनों उसी एक परम सत्य की अभिव्यक्तियाँ हैं। अंतर केवल चेतना और संवेदनशीलता की जटिलता का है, तात्विक सार का नहीं।
	</p>
	<p>
		अद्वैत कर्तव्य, संघर्ष या प्रकृति के भौतिक नियमों को समाप्त नहीं करता; यह उन्हें व्यापक संदर्भ में देखता है।
	</p>
	<h3>योद्धा का अस्तित्व क्यों आवश्यक है?</h3>
	<p>
		अहिंसा को एक निरपेक्ष हठधर्मिता मानने की मूल त्रुटि यह पूर्वधारणा है कि सभी मनुष्य एक साथ आध्यात्मिक रूप से विकसित हो जाएंगे।
	</p>
	<p>
		वे ऐसा नहीं करेंगे।
	</p>
	<p>
		'द लॉ ऑफ़ वन' की शब्दावली में, ऐसी सत्ताएँ और चेतनाएँ हैं जो पूरी तरह 'स्व-सेवा' (service-to-self) के ध्रुवीकरण पर काम करती हैं—जिनका उद्देश्य प्रभुत्व, दमन, नियंत्रण और शोषण है। व्यावहारिक शब्दों में, संसार में हमेशा शिकारी, आक्रांता और अजमल कसाब जैसे आतंकवादी मौजूद रहेंगे।
	</p>
	<p>
		यदि कोई समाज बल प्रयोग की अपनी पूरी क्षमता को त्याग देता है और यह मान बैठता है कि हिंसा का कोई भी कृत्य आध्यात्मिक पतन है, तो इससे सार्वभौमिक शांति स्थापित नहीं होती। वह समाज केवल स्वयं को 'मवेशी' बना लेता है। और मवेशियों को वे लोग हमेशा अपना शिकार, गुलाम और भोजन बनाते हैं जो अपने पंजों को तेज रखते हैं।
	</p>
	<p>
		माँ दुर्गा अपने दसों हाथों में केवल कमल के फूल नहीं थामतीं। उनके हाथों में त्रिशूल, खड्ग, चक्र, धनुष और परशु हैं। वे महिषासुरमर्दिनी हैं—महिषासुर रूपी दैत्य का संहार करने वाली।
	</p>
	<p>
		बलि का अनुष्ठान इसी यथार्थ का प्रत्यक्ष भौतिक स्मरण कराता है:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>दानव का संहार होना अनिवार्य है।</strong></div></li>
		<li><div><strong>शस्त्र उठाने, जीवन समाप्त करने और रक्त का सामना करने की क्षमता को न तो भुलाया जा सकता है और न ही दूसरों पर छोड़ा जा सकता है।</strong></div></li>
		<li><div><strong>रक्षा की शक्ति के बिना करुणा केवल असहायता है जो सदाचार का ढोंग करती है।</strong></div></li>
	</ul>
	<p>
		जब देवी के समक्ष किसी जीव की बलि दी जाती है, तो साधक को मृत्यु की आँखों में सीधे देखना पड़ता है। यह आधुनिक समाज द्वारा जीवन, भोजन और उत्तरजीविता के बीच बनाई गई कृत्रिम दूरी को समाप्त कर देता है। यह याद दिलाता है कि जब धर्म को दुष्टों से निपटने की आवश्यकता हो, तो मनुष्य को दर्शक नहीं, संहारक बनने के लिए तैयार रहना चाहिए।
	</p>
	<h3>आधुनिक पाखंड</h3>
	<p>
		पशु बलि पर होने वाले अधिकांश आधुनिक आक्रोश में गहरा दार्शनिक विरोधाभास है।
	</p>
	<p>
		दुनिया भर में हर साल अरबों जानवरों को केवल स्वाद और जिह्वा के सुख के लिए—जिसे कमजोरों का भोग कहा जा सकता है—क्रूर, यांत्रिक वधशालाओं में काटा जाता है। उन्हें बिना किसी कृतज्ञता या पवित्रता के मारा जाता है और प्लास्टिक में लपेटकर बेचा जाता है ताकि उपभोक्ता को रक्त न देखना पड़े।
	</p>
	<p>
		लेकिन जब किसी पवित्र अनुष्ठान में देवी को बलि दी जाती है—जहाँ प्रकृति के संहार चक्र को स्वीकार किया जाता है, लिए गए जीवन का सम्मान किया जाता है और उसे प्रसाद के रूप में ग्रहण किया जाता है—तो उसे बर्बरता करार दे दिया जाता है।
	</p>
	<p>
		जब तक मानवता अपनी क्षुधा के लिए जानवरों को पालना और मारना बंद नहीं करती, तब तक अनुष्ठानिक बलि की निंदा करना केवल पाखंड है। कम से कम मंदिर का यह अनुष्ठान मनुष्य को किसी जीवन को समाप्त करने की गंभीरता का सीधा सामना कराता है, कसाई के काउंटर के पीछे छिपने नहीं देता।
	</p>
	<h3>यथार्थ का सामना</h3>
	<p>
		पशु बलि का अनुष्ठान केवल तभी अपनी सार्थकता खोएगा जब संसार से बुराई पूरी तरह मिट जाएगी, कोई हिंसक आक्रांता नहीं बचेगा और प्रत्येक चेतना आत्मरक्षा और उत्तरजीविता की सीमाओं से परे चली जाएगी।
	</p>
	<p>
		जब तक वह स्वर्णिम काल नहीं आता, यह संसार सृजन और संहार दोनों का रंगमंच बना रहेगा।
	</p>
	<p>
		हमें अपने आंतरिक विकारों की बलि अवश्य देनी चाहिए, किन्तु जो लोग शांति के स्थान पर दमन को चुनते हैं, उनके विरुद्ध निर्दोषों की रक्षा करने का सामर्थ्य हमें कभी नहीं छोड़ना चाहिए। बलि क्रूरता का उत्सव नहीं है; यह मृत्यु, कर्तव्य और सत्य के रौद्र रूप का एक निर्भीक साक्षात्कार है।
	</p>
