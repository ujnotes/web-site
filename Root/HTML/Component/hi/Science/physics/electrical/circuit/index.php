		<h3>विद्युत परिपथ क्या है?</h3>
	<p>
		विद्युत परिपथ एक अखंड संवाहक लूप है जो विद्युत आवेश को एक शक्ति स्रोत से, एक या अधिक घटकों के माध्यम से, और वापस स्रोत तक निरंतर प्रवाहित होने की अनुमति देता है।
	</p>
	<p>
		यदि लूप किसी भी बिंदु पर टूट जाता है, तो आवेश पथ पूरा नहीं कर सकते, विद्युत क्षेत्र समाप्त हो जाता है, और उस शाखा में धारा तुरंत रुक जाती है।
	</p>
	<h3>परिपथ को कार्य करने के लिए क्या आवश्यक है?</h3>
	<p>
		प्रत्येक कार्यशील परिपथ के लिए कम से कम तीन आवश्यक तत्वों की आवश्यकता होती है:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>विद्युत वाहक बल का स्रोत</strong>: एक बैटरी, जनरेटर, या सौर सेल जो अपने टर्मिनलों के बीच विद्युत विभवांतर (वोल्टता) बनाए रखता है।</div></li>
		<li><div><strong>एक संवाहक पथ</strong>: तांबे के तार, मुद्रित सर्किट बोर्ड (PCB) के निशान, या धातु के ट्रैक जो कम प्रतिरोध के साथ गतिमान आवेश वाहक प्रदान करते हैं।</div></li>
		<li><div><strong>एक लोड (भार)</strong>: एक घटक जैसे कि प्रतिरोधक, लैंप, हीटिंग तत्व, या मोटर जो विद्युत ऊर्जा को ऊष्मा, प्रकाश, या यांत्रिक कार्य में परिवर्तित करता है।</div></li>
	</ul>
	<p>
		अधिकांश व्यावहारिक परिपथों में तारों को काटे बिना संवाहक लूप को सुरक्षित रूप से खोलने और बंद करने के लिए एक स्विच या नियंत्रण तत्व भी शामिल होता है।
	</p>
	<h3>बंद, खुला और शॉर्ट परिपथ</h3>
	<p>
		जब कोई परिपथ सामान्य रूप से काम कर रहा होता है, तो वह एक <strong>बंद परिपथ (closed circuit)</strong> होता है: आवेश लगातार घूमते हैं, लोड पर विभव गिरता है, और ऊर्जा स्रोत से लोड तक सुचारू रूप से स्थानांतरित होती है।
	</p>
	<p>
		जब कोई कनेक्शन टूट जाता है या स्विच बंद कर दिया जाता है, तो यह एक <strong>खुला परिपथ (open circuit)</strong> बन जाता है। हवा का प्रतिरोध अत्यधिक होता है, इसलिए धारा तुरंत शून्य हो जाती है, भले ही शक्ति स्रोत अंतराल के पार वोल्टेज बनाए रखना जारी रखे।
	</p>
	<p>
		एक <strong>शॉर्ट परिपथ (short circuit)</strong> तब होता है जब एक अनपेक्षित कम-प्रतिरोध वाला कनेक्शन लोड को पूरी तरह से बायपास कर देता है। क्योंकि परिपथ का प्रतिरोध शून्य के करीब गिर जाता है, ओम का नियम (<strong>I = V / R</strong>) बताता है कि धारा खतरनाक स्तर तक बढ़ जाती है, जिससे इन्सुलेशन पिघल सकता है, फ़्यूज़ उड़ सकते हैं, या आग लग सकती है।
	</p>
	<h3>श्रेणी और समानांतर संयोजन</h3>
	<p>
		घटक दो मूलभूत विन्यासों में आपस में जुड़ते हैं:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>श्रेणी परिपथ (Series circuits)</strong>: घटक एक ही निरंतर पथ पर क्रमिक रूप से व्यवस्थित होते हैं। प्रत्येक घटक से समान धारा बहती है, जबकि कुल आपूर्ति वोल्टेज उनके बीच विभाजित हो जाता है। यदि कोई एक घटक विफल या डिस्कनेक्ट हो जाता है, तो पूरा परिपथ खुल जाता है और सभी घटक बंद हो जाते हैं।</div></li>
		<li><div><strong>समानांतर परिपथ (Parallel circuits)</strong>: घटक साझा सामान्य जंक्शनों से जुड़े होते हैं। प्रत्येक शाखा को पूरा स्रोत वोल्टेज मिलता है, जबकि कुल धारा उनके व्यक्तिगत प्रतिरोध के अनुसार शाखाओं में विभाजित होती है। यदि एक शाखा डिस्कनेक्ट हो जाती है, तो अन्य सभी शाखाएँ बिना किसी रुकावट के काम करती रहती हैं।</div></li>
	</ul>
	<p>
		घरेलू वायरिंग लगभग विशेष रूप से समानांतर में की जाती है ताकि टेबल लैंप बंद करने से कंप्यूटर या रेफ्रिजरेटर बंद न हो।
	</p>
