		<li><div><strong>समूह का वेग:</strong> भीड़ का शोर निजी आवाज और तर्क दबाता है।</div></li>
		<li><div><strong>आत्म-पुष्टि:</strong> स्थानीय लोकप्रियता को ही सत्य का प्रमाण माना जाता है।</div></li>
		<li><div><strong>अधिकार-बोध:</strong> बड़े समर्थन के कारण लोग बिना तर्क स्वयं को सही और अधिकारी मानते हैं।</div></li>
