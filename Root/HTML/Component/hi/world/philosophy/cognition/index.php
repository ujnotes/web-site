	</p>
	<p>
		बुद्धिमत्ता बताती है कि वे प्रक्रियाएँ कितनी प्रभावी समझ और उपयोगी कर्म पैदा करती हैं।
	</p>
	<p>
		फोन नम्बर याद करना संज्ञान है; कठिन समस्या का पैटर्न पहचानना बुद्धिमत्ता है। दोनों जुड़ी हैं पर एक नहीं।
	</p>
