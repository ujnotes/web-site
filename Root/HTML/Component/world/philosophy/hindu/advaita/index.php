	<h3>What does non-duality mean?</h3>
	<p>
		In ordinary life I experience myself as one thing and the world as another. There is “me” here and everything else out there.
	</p>
	<p>
		Advaita asks whether this separation is final.
	</p>
	<p>
		Think of many pots filled with space. The pots have different shapes and names, but the space inside them was never truly separate from the space outside. The pot creates a boundary in our view, not in space itself.
	</p>
	<p>
		Advaita says that our individual identities work in a similar way. At the everyday level we are different people. At the deepest level, consciousness is not divided in the way it appears.
	</p>
	<h3>Is Brahman a personal god?</h3>
	<p>
		Not in the ordinary sense.
	</p>
	<p>
		Brahman is not a supernatural person sitting outside the universe and managing it. It is the non-dual reality of all things.
	</p>
	<p>
		Advaita is therefore not straightforward atheism. It accepts an ultimate reality. But that reality is not the personal creator god rejected by many atheists.
	</p>
	<h3>What are maya and avidya?</h3>
	<p>
		<strong>Maya</strong> is the appearance of plurality and separation. <strong>Avidya</strong> is ignorance: mistaking that appearance for the whole truth.
	</p>
	<p>
		A rope seen in poor light may look like a snake. The fear is real, but it rests on a mistake. Better light does not destroy the snake; it shows that the snake was never there as imagined.
	</p>
	<p>
		Advaita uses this kind of example to explain liberation. The problem is not that reality must be replaced. The mistake in our understanding must be seen clearly.
	</p>
	<h3>Where do karma and dharma fit?</h3>
	<p>
		<strong>Karma</strong> means action and its consequences. Our choices create habits, shape character and affect other lives. Many Hindu traditions also understand karma across rebirths.
	</p>
	<p>
		Advaita says that liberating knowledge ends the deepest ignorance. But this does not make conduct unimportant. A confused and restless mind is not ready to see clearly. Dharma, self-restraint and honest action prepare the mind for knowledge.
