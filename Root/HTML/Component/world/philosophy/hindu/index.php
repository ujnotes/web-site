	<p>
		<strong>Dharma</strong> is the responsibility to live rightly.
	</p>
	<p>
		It concerns truth, justice, restraint, compassion and our duties towards other lives. It is not simply an order given by God. It asks a practical question: what should I do here?
	</p>
