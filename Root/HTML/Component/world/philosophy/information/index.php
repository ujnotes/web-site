	<h2 class='center'><?php echo $desc; ?></h2>
	<h3>What is information?</h3>
	<p>
		Information is a difference or arrangement that tells us something.
	</p>
	<p>
		A footprint in wet ground contains information about something that passed. A change in the sky may contain information about approaching weather. A sequence of marks on a page may contain information when someone knows how to read them.
	</p>
	<p>
		Information does not have to give a complete answer. It only needs to change what can be known, expected or done.
	</p>
	<p>
		In short, information is a meaningful difference.
	</p>
	<h3>Where does information begin?</h3>
	<p>
		Information begins with distinction.
	</p>
	<p>
		If every part of a perfectly blank page is identical, no part tells us anything more than another. Make one mark upon it and a distinction appears: marked and unmarked.
	</p>
	<p>
		A light may be on or off. A door may be open or closed. A sound may be high or low. A container may be full or empty.
	</p>
	<p>
		The difference between possible states allows one state to stand for something.
	</p>
	<p>
		Without difference there can be no signal. Without possible alternatives, nothing new can be learned from observing which alternative occurred.
	</p>
	<h3>Is every difference information?</h3>
	<p>
		Not automatically.
	</p>
	<p>
		A difference becomes information for a system when it can be detected and can affect interpretation or action.
	</p>
	<p>
		A trail of chemicals may guide an ant while meaning nothing to a stone. Radio waves may carry a message through a room while remaining imperceptible to a person without a receiver.
	</p>
	<p>
		The same physical change can therefore be informative to one system and unnoticed by another.
	</p>
	<p>
		Information depends upon a relationship between:
	</p>
	<ul class="list-bullet content-list">
		<li><div>Something that can vary</div></li>
		<li><div>A system capable of detecting the variation</div></li>
		<li><div>A way in which that variation matters</div></li>
	</ul>
	<h3>What is a signal?</h3>
	<p>
		A signal is a physical change used to carry information.
	</p>
	<p>
		Sound carries information through variations in air pressure. Writing carries information through arrangements of visible marks. Nerves carry information through electrochemical activity. Electronic devices use changing voltages, currents, light or magnetic states.
	</p>
	<p>
		A signal is not the information itself in isolation. It is the physical form through which the information becomes available.
	</p>
	<p>
		The same information can travel through different signals. A sentence may be spoken, written, printed as raised dots or transmitted electrically. Its physical carrier changes while much of its informational structure is preserved.
	</p>
	<h3>What is data?</h3>
	<p>
		Data is information represented in a form that can be stored, transmitted or processed.
	</p>
	<p>
		A temperature in the world is a physical condition. The reading <strong>32°C</strong> is data representing that condition.
	</p>
	<p>
		A person's face reflects light. A digital photograph stores measurements derived from that light as data.
	</p>
	<p>
		Data is therefore not the thing itself. It is a representation of selected aspects of the thing.
	</p>
	<p>
		The distinction is useful:
	</p>
	<ul class="list-bullet content-list">
		<li><div><strong>Reality</strong> is what exists or happens.</div></li>
		<li><div><strong>Signals</strong> are detectable physical changes.</div></li>
		<li><div><strong>Data</strong> is information arranged into a usable representation.</div></li>
		<li><div><strong>Meaning</strong> is what a system takes that representation to indicate.</div></li>
	</ul>
	<h3>What is representation?</h3>
	<p>
		A representation is something used in place of something else.
	</p>
	<p>
		A map represents a place. A word represents an object, action or idea. A number may represent a quantity. A red lamp may represent danger or the command to stop.
	</p>
	<p>
		The representation does not need to resemble what it represents. The word <em>tree</em> is not shaped like a tree. Its meaning comes from an established relationship between the symbol and what it refers to.
	</p>
	<p>
		Representations allow absent things to influence the present. A traveller can plan using a map without seeing the entire land. A computer can process a stored temperature without containing the heat itself. A mind can consider tomorrow before tomorrow arrives.
	</p>
	<h3>Does information require meaning?</h3>
	<p>
		There are two useful senses of information.
	</p>
	<p>
		In the technical sense, information concerns which state occurred among several possibilities. Receiving a signal can reduce uncertainty even before anyone understands its wider significance.
	</p>
	<p>
		In the ordinary sense, information is connected with meaning. The receiver knows what the signal is about and can relate it to other knowledge.
	</p>
	<p>
		A string of unfamiliar symbols may contain a precise message even though a particular reader cannot understand it. The informational pattern exists, but its meaning is unavailable to that reader.
	</p>
	<p>
		Information can therefore be carried without being understood.
	</p>
	<h3>How is information encoded?</h3>
	<p>
		Encoding is the use of an agreed system to represent information.
	</p>
	<p>
		Languages encode ideas into sounds or marks. Musical notation encodes instructions for producing music. A clock encodes time through the positions of its hands. Digital systems encode information into patterns of bits.
	</p>
	<p>
		An encoding requires rules connecting represented states with their intended interpretation.
	</p>
	<p>
		The pattern <strong>01000001</strong> is not inherently the letter A. It represents A only under an encoding that assigns that pattern to the letter. Under another interpretation, the same pattern may be the number 65, part of a colour or one fragment of an instruction.
	</p>
	<p>
		The pattern remains the same. Its interpretation depends on the code.
	</p>
	<h3>Is information physical?</h3>
	<p>
		Information must be physically represented in order to exist, travel or have an effect.
	</p>
	<p>
		A memory requires some persistent arrangement of matter or energy. A message needs a carrier. Even a thought depends upon activity and structure in a living brain.
	</p>
	<p>
		But information is not identical to any one physical form.
	</p>
	<p>
		The same poem can exist as ink on paper, magnetic states on a drive, electrical activity in memory or patterns of sound in the air. The physical representations differ while the organized relationships that carry the poem remain recognizable.
	</p>
	<p>
		Information is embodied physically but described through pattern and relationship.
	</p>
	<h3>How is information stored?</h3>
	<p>
		Information is stored when a physical state is preserved well enough to be read later.
	</p>
	<p>
		A groove in stone, ink on paper, magnetization on a disk and strengthened connections in a brain can all function as memory.
	</p>
	<p>
		Storage does not preserve the original event. It preserves a representation capable of affecting a future system.
	</p>
	<p>
		A photograph does not preserve the moment itself. It preserves a pattern from which aspects of that moment can later be reconstructed.
	</p>
	<p>
		Every method of storage has limits. Physical states can fade, decay, be overwritten or become unreadable when the method of interpretation is lost.
	</p>
	<h3>How is information communicated?</h3>
	<p>
		Communication transfers a representation from a sender to a receiver.
	</p>
	<p>
		A basic communication process contains:
	</p>
	<ul class="list-bullet content-list">
		<li><div>A source of information</div></li>
		<li><div>An encoding</div></li>
		<li><div>A physical signal</div></li>
		<li><div>A channel through which it travels</div></li>
		<li><div>A receiver capable of detecting it</div></li>
		<li><div>A decoding or interpretation</div></li>
	</ul>
	<p>
		Successful communication does not require the receiver to reproduce the exact physical signal sent by the source. It requires the relevant pattern to survive the journey.
	</p>
	<p>
		A spoken sentence may become pressure waves, electrical signals, stored numbers, radio waves and then pressure waves again. The carrier changes repeatedly while the message is preserved.
	</p>
	<h3>What is noise?</h3>
	<p>
		Noise is any disturbance that makes the received signal differ from the intended one.
	</p>
	<p>
		A smudged letter, a broken wire, an interrupted radio signal and a mistaken memory can all introduce error.
	</p>
	<p>
		Information systems resist noise by adding structure:
	</p>
	<ul class="list-bullet content-list">
		<li><div>Repetition</div></li>
		<li><div>Error-detecting patterns</div></li>
		<li><div>Redundant copies</div></li>
		<li><div>Context</div></li>
		<li><div>Confirmation from another source</div></li>
	</ul>
	<p>
		Redundancy may appear wasteful because it repeats information. But repetition can make a message recoverable when part of it is damaged.
	</p>
	<h3>Can information be compressed?</h3>
	<p>
		Yes.
	</p>
	<p>
		Compression represents the same useful information with fewer symbols or states by taking advantage of regularity.
	</p>
	<p>
		Instead of writing “red, red, red, red, red,” one may write “red five times.” A repeated pattern has been replaced by a shorter description.
	</p>
	<p>
		Compression may be <strong>lossless</strong>, allowing the original data to be reconstructed exactly, or <strong>lossy</strong>, preserving what matters while discarding selected detail.
	</p>
	<p>
		A written summary is a form of lossy compression. It does not preserve every word of the source, but it attempts to preserve the important relationships.
	</p>
	<p>
		Concepts and models also compress information. The concept <em>chair</em> lets the mind recognize many different objects without remembering every detail of every chair previously seen.
	</p>
	<h3>Is more information always better?</h3>
	<p>
		No.
	</p>
	<p>
		Information has value in relation to a purpose.
	</p>
	<p>
		The colour of a distant wall may be irrelevant when deciding whether it is safe to cross a road. The speed and direction of an approaching vehicle are important.
	</p>
	<p>
		Too much unorganized information can conceal what matters. Incorrect or misleading information can produce worse decisions than acknowledged ignorance.
	</p>
	<p>
		A capable system must therefore do more than collect information. It must select, organize, test and relate it.
	</p>
	<h3>Is information the same as knowledge?</h3>
	<p>
		No.
	</p>
	<p>
		Information is what becomes available through signals, observations or representations.
	</p>
	<p>
		Knowledge is information that has been organized and retained within a model of how things are related.
	</p>
	<p>
		A weather report supplies information. Knowing how weather conditions affect a particular journey requires connections between that report, past experience, location and purpose.
	</p>
	<p>
		Information may arrive in a moment. Knowledge is built by integrating information so that it can guide future interpretation and action.
	</p>
	<h3>How do computers use information?</h3>
	<p>
		A <a class="content-link XURL" href="/computer" data-target="computer" data-title="computer">computer</a> receives physical signals and treats their states as representations.
	</p>
	<p>
		It stores those representations as data, transforms them according to instructions and produces new representations or physical actions.
	</p>
	<p>
		The computer does not work with temperature, music, language or money directly. It works with physical states that have been made to represent those things.
	</p>
	<p>
		This separation is what makes a general-purpose computer possible. Once many kinds of things are represented as data, the same machine can store and transform them using common operations.
	</p>
	<h3>How does information relate to cognition?</h3>
	<p>
		Cognition begins when a living or artificial system does more than merely carry a signal.
	</p>
	<p>
		It selects information, interprets it, combines it with memory, forms concepts, predicts possibilities and uses the result to guide action.
	</p>
	<p>
		Information is the material upon which cognition works.
	</p>
	<p>
		But information alone is not cognition, just as a library is not a reader. There must also be a system that organizes and uses what is available.
	</p>
	<h3>Can information be false?</h3>
	<p>
		A physical signal simply has the state it has. But what it represents can be inaccurate.
	</p>
	<p>
		A faulty thermometer may display the wrong temperature. A fabricated report may describe an event that never happened. A correct message may be misunderstood because the receiver uses the wrong interpretation.
	</p>
	<p>
		Information should therefore be judged at several levels:
	</p>
	<ul class="list-bullet content-list">
		<li><div>Was the signal received correctly?</div></li>
		<li><div>Was it decoded correctly?</div></li>
		<li><div>Does the representation correspond to reality?</div></li>
		<li><div>Is it complete enough for the intended decision?</div></li>
		<li><div>Is the source trustworthy?</div></li>
	</ul>
	<p>
		A clear message is not necessarily a true message.
	</p>
	<h3>So what is information, finally?</h3>
	<p>
		Information is a detectable difference or organized pattern that can change what a system knows, expects or does.
	</p>
	<p>
		It is carried by physical signals, arranged as data, interpreted through codes and integrated into knowledge.
	</p>
	<p>
		Information can be stored, transmitted, copied, compressed, corrupted and corrected. It may exist without being understood, and it may be perfectly communicated while still being false.
	</p>
	<p>
		It is the bridge between change in the world and change within a mind or machine.
	</p>

</div>

